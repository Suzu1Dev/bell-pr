#!/usr/bin/env node
// Product metadata for standalone installers and the Homebrew tap. Refresh the
// formula only after publishing package.json's version to npm; normal checks
// are offline. The formula hashes the published tarball, not a local repack.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readProduct } from "./sync-package-meta.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = readFileSync(path.join(root, "shared/product.ts"), "utf8");
const product = readProduct(source);
const bins = JSON.parse(/\bbinNames:\s*(\[[^\]]*\])/.exec(source)?.[1] ?? "[]");
const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const mode = process.argv[2];
const formulaPath = path.join(root, "Formula", `${product.npmPackage}.rb`);
const marker = /# BEGIN GENERATED PRODUCT METADATA\r?\n[^]*?# END GENERATED PRODUCT METADATA/;
const quote = (value) => `'${value.replaceAll("'", "'\\''")}'`;

async function main() {
  if (process.argv.length !== 3 || !["--check", "--write", "--refresh-formula"].includes(mode))
    throw new Error("Usage: node scripts/sync-installers.mjs --check|--write|--refresh-formula");
  if (!/^[a-z0-9][a-z0-9-]*$/.test(product.npmPackage) ||
      !bins.length || bins.some((bin) => !/^[a-z0-9][a-z0-9-]*$/.test(bin)) ||
      !/^https:\/\/github\.com\/[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(product.publicRepoUrl))
    throw new Error("Installers need a public GitHub repository, npm package and command names in shared/product.ts.");
  let stale = false;
  const update = (relative, expected) => {
    const file = path.join(root, relative);
    let actual;
    const bytes = Buffer.isBuffer(expected) ? expected : Buffer.from(expected);
    try { actual = readFileSync(file); } catch { /* A new generated file. */ }
    if (actual?.equals(bytes)) return;
    if (mode === "--check") {
      console.error(`sync-installers: stale ${relative}`);
      stale = true;
    } else {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, bytes);
      console.log(`sync-installers: updated ${relative}`);
    }
  };
  const shellMetadata = [
    `BELLPR_PACKAGE=${quote(product.npmPackage)}`,
    `BELLPR_PRODUCT=${quote(product.name)}`,
    `BELLPR_BIN=${quote(bins[0])}`,
  ].join("\n");
  for (const relative of ["install.sh", "scripts/install-wsl.sh", "install.ps1"]) {
    const text = readFileSync(path.join(root, relative), "utf8");
    if (!marker.test(text)) throw new Error(`${relative}: missing generated metadata markers`);
    const metadata = relative.endsWith(".ps1")
      ? `$InstallerRepository = '${product.publicRepoUrl}'\n$InstallerRef = 'main'\n$InstallerHomepage = '${product.homepageUrl.replaceAll("'", "''")}'`
      : shellMetadata;
    update(relative, text.replace(marker, `# BEGIN GENERATED PRODUCT METADATA\n${metadata}\n# END GENERATED PRODUCT METADATA`));
  }
  for (const [original, copy] of [
    ["install.sh", "site/install"],
    ["install.ps1", "site/install.ps1"],
    ["scripts/install-wsl.sh", "site/install-wsl.sh"],
  ]) update(copy, readFileSync(path.join(root, original)));
  let sha;
  let formulaVersion = pkg.version;
  if (mode === "--refresh-formula") {
    const metadataUrl = `https://registry.npmjs.org/${product.npmPackage}/${pkg.version}`;
    const metadataResponse = await fetch(metadataUrl);
    if (!metadataResponse.ok) throw new Error(`Publish ${pkg.version} to npm first (${metadataResponse.status}).`);
    const metadata = await metadataResponse.json();
    const expectedUrl = `https://registry.npmjs.org/${product.npmPackage}/-/${product.npmPackage}-${pkg.version}.tgz`;
    if (metadata.name !== product.npmPackage || metadata.version !== pkg.version || metadata.dist?.tarball !== expectedUrl)
      throw new Error("Unexpected npm metadata or tarball origin.");
    const response = await fetch(expectedUrl);
    if (!response.ok) throw new Error(`Tarball download failed (${response.status}).`);
    const bytes = Buffer.from(await response.arrayBuffer());
    const integrity = `sha512-${createHash("sha512").update(bytes).digest("base64")}`;
    if (metadata.dist.integrity !== integrity) throw new Error("Published npm tarball integrity mismatch.");
    sha = createHash("sha256").update(bytes).digest("hex");
  } else {
    const formula = readFileSync(formulaPath, "utf8");
    sha = /^ {2}sha256 "([a-f0-9]{64})"$/m.exec(formula)?.[1];
    formulaVersion = /^ {2}version "(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)"$/m.exec(formula)?.[1];
    if (!sha || !formulaVersion)
      throw new Error("Run --refresh-formula after publishing a version to npm.");
  }
  update(path.relative(root, formulaPath), `# Generated by scripts/sync-installers.mjs from shared/product.ts and npm.
class ${product.npmPackage.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("")} < Formula
  desc "Local workbench for AI-assisted open-source contributions"
  homepage "${product.publicRepoUrl}"
  url "https://registry.npmjs.org/${product.npmPackage}/-/${product.npmPackage}-${formulaVersion}.tgz"
  version "${formulaVersion}"
  sha256 "${sha}"
  license "${pkg.license}"

  depends_on "node"
  depends_on "git"
  depends_on "gh"

  def install
    system "npm", "install", *std_npm_args
    bin.install_symlink libexec.glob("bin/*")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/${bins[0]} --version")
    assert_match "doctor", shell_output("#{bin}/${bins[0]} --help")
  end
end
`);
  if (stale) process.exitCode = 1;
  else console.log("sync-installers: metadata, website copies and Homebrew formula are current.");
}

main().catch((error) => {
  console.error(`sync-installers: ${error.message}`);
  process.exitCode = 1;
});
