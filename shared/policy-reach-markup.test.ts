// A rule's quote keeps the file's own Markdown (emphasis, code marks,
// links), which split the words the reach reads: "No **AI tools** may be
// used in the *creation* of a contribution." read as an output ban, so a
// carve-out beside it gave a fitted Learn-by-hand run the quoted confirm.
// The reach reads a quote as a reader sees it. Written for these tests.
import assert from "node:assert/strict";
import test from "node:test";
import { byHandRulesCase } from "./by-hand-rules.js";
import { areaReach, banReach } from "./policy-reach.js";
import { attachCarveOuts, classifyPolicy } from "./project-policy.js";

test("emphasis, code marks and links inside a quote don't hide what it reaches", () => {
  for (const quote of [
    "No **AI tools** may be used in the *creation* of a contribution.",
    "Contributions that **use** AI are declined, and so is AI-generated code.",
    "Do not use `ChatGPT` to generate patches.",
    "Patches made with the [help of AI](ai.md) or generated by it are declined.",
    "Contributions created __with the help__ of LLMs are declined.",
  ])
    assert.equal(banReach(quote), "assistance", quote);
  assert.equal(areaReach("Do not **use** AI-generated fixes on `good first issue`s."), "use");
  // Markup alone never turns a rule into an output one.
  assert.equal(banReach("But not to **create**."), "output");
  assert.equal(banReach("AI-**generated** code is not accepted."), "output");
  assert.equal(banReach("Pull requests made with *AI tools* are not accepted."), "unknown");
});

test("an emphasised assistance ban next to a carve-out gives no quoted confirm", () => {
  const text = [
    "No **AI tools** may be used in the *creation* of a contribution.",
    "",
    "This policy does not apply to using AI to understand the code or to research APIs.",
  ].join("\n");
  const rules = {
    checkedAt: "2026-10-20T10:00:00.000Z",
    findings: attachCarveOuts("CONTRIBUTING.md", text, classifyPolicy("CONTRIBUTING.md", text)),
    filesRead: ["CONTRIBUTING.md"],
  };
  assert.deepEqual(
    rules.findings.map((finding) => [finding.kind, finding.contribution, !!finding.allows]),
    [["ban", true, true]],
  );
  const result = byHandRulesCase(rules, { learningIssue: false, now: "2026-10-20T09:00:00.000Z" });
  assert.deepEqual(result.case === "blocked" && [result.reason, result.reach], ["reach", "assistance"]);
});
