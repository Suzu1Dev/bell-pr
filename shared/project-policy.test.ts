// The fixtures are short snippets written for these tests, modelled on the
// structure of real projects' policies (plan research/maintainers.md); they
// are not copies of any project's files.
import test from "node:test";
import assert from "node:assert/strict";
import { aiDisclosureLine } from "./drafts.js";
import {
  classifyPolicy,
  disclosureRule,
  hasAiDisclosure,
  rawProse,
} from "./project-policy.js";

const kinds = (path: string, text: string) =>
  classifyPolicy(path, text).map((finding) => [finding.kind, finding.contribution]);

/** Every quote is verbatim: its text starts on the line it names. */
function assertVerbatim(text: string, path = "AI_POLICY.md") {
  const lines = text.split("\n");
  const findings = classifyPolicy(path, text);
  for (const finding of findings) {
    assert.ok(finding.quote.length <= 300, finding.quote);
    assert.equal(finding.path, path);
    const firstWords = finding.quote.split(" ").slice(0, 3).join(" ");
    assert.ok(
      lines[finding.line - 1].includes(firstWords),
      `line ${finding.line} should hold "${firstWords}"`,
    );
    assert.ok(text.replace(/\s*\n\s*/g, " ").includes(finding.quote), finding.quote);
  }
  return findings;
}

test("rawProse keeps HTML comments and skips fenced code, with the original line numbers", () => {
  const text = "# Title\n<!-- a rule in a comment -->\n```sh\nno AI here\n```\nAfter the code.\n~~~\n``` not a close\n~~~\nEnd.";
  assert.deepEqual(rawProse(text), [
    { line: 1, text: "# Title" },
    { line: 2, text: "<!-- a rule in a comment -->" },
    { line: 6, text: "After the code." },
    { line: 10, text: "End." },
  ]);
});

test("a policy refusing AI-generated pull requests is a ban with contribution context", () => {
  const text = [
    "# AI usage policy",
    "",
    "We are a small team and review every change by hand.",
    "",
    "AI-generated pull requests",
    "will be closed without review.",
  ].join("\n");
  const findings = assertVerbatim(text);
  assert.deepEqual(
    findings.map((finding) => [finding.kind, finding.contribution, finding.line]),
    [["ban", true, 5]],
  );
  assert.equal(findings[0].quote, "AI-generated pull requests will be closed without review.");
  // The same refusal without naming a contribution is ambiguous, never a block.
  assert.deepEqual(kinds("AI_POLICY.md", "We do not use AI tools in our own release process."), [
    ["ban", false],
  ]);
});

test("a refusal of AI-generated code or changes to the project is a ban with contribution context", () => {
  for (const text of [
    "We do not accept AI-generated code.",
    "AI-generated code will not be merged.",
    "Do not use ChatGPT, Copilot or other AI tools to write code for this project.",
    "The use of AI coding assistants is not allowed in this project.",
    "Code generated by a language model is not welcome in this project.",
    "Code generated by AI tools must not be committed without prior written approval.",
    "Contributions must not include content generated by large language models.",
    "Code generated by a large language model or similar technology, such as GitHub's Copilot or OpenAI's ChatGPT, is presumed to be tainted code, and must not be committed without prior written approval by core.",
  ])
    assert.deepEqual(kinds("CONTRIBUTING.md", text), [["ban", true]], text);
  // Issues, the code of conduct or another project's pages are not the change.
  for (const text of [
    "AI-generated issues are not welcome in our project's tracker.",
    "AI-generated content violates our code of conduct and is not allowed.",
  ])
    assert.deepEqual(kinds("CONTRIBUTING.md", text), [["ban", false]], text);
});

test("a refusal with a condition the contributor meets is ambiguous, never a block", () => {
  // Reviewed, understood or disclosed AI help is welcome here, and BELL
  // asks for all three itself.
  const text = [
    "# AI usage policy",
    "",
    "We welcome contributors who use AI tools as a learning aid.",
    "",
    "Pull requests that consist of AI-generated code the author",
    "has not reviewed and edited will be closed without review.",
  ].join("\n");
  assert.deepEqual(
    assertVerbatim(text).map((finding) => [finding.kind, finding.contribution, finding.line]),
    [["ban", false, 5]],
  );
  for (const text of [
    "Do not submit AI-generated code that you do not understand.",
    "Please don't submit pull requests made with AI tools unless you have reviewed every line.",
    "Contributors must not submit LLM output they cannot explain.",
    "We do not accept low-effort AI-generated pull requests.",
  ])
    assert.deepEqual(kinds("CONTRIBUTING.md", text), [["ban", false]], text);
  // A refusal without disclosure asks for the disclosure.
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "We will not accept AI-generated contributions without disclosure."),
    [
      ["ban", false],
      ["disclose", true],
    ],
  );
  // Permission only the maintainers give is not such a condition.
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "AI-generated pull requests will be closed unless approved by a maintainer."),
    [["ban", true]],
  );
});

test("a rule about the description or comments is not a ban of AI-assisted changes", () => {
  for (const text of [
    "The PR description and comments must be written by the contributor, with no AI assistance beyond grammar or English translations.",
    "Do not use AI tools to write pull request descriptions or comments; write them yourself.",
    "Do not use AI tools to write the PR description; write it yourself.",
  ])
    assert.deepEqual(kinds("CONTRIBUTING.md", text), [["own-words", true]], text);
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "Do not use AI tools to respond to review comments on your pull request."),
    [["ban", false]],
  );
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "LLM output is prohibited for any direct communication with maintainers."),
    [["ban", false]],
  );
  // The change itself named next to the description stays a ban.
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "Do not use AI tools to write pull requests or their descriptions."),
    [["ban", true]],
  );
});

test("a rule inside an HTML comment of a pull request template is found", () => {
  const text = [
    "<!--",
    "If you used AI tools to write this pull request, you must disclose that",
    "in the description, and explain your work in your own words.",
    "-->",
    "",
    "## Summary",
  ].join("\n");
  const findings = assertVerbatim(text, ".github/pull_request_template.md");
  assert.deepEqual(
    findings.map((finding) => [finding.kind, finding.line]),
    [
      ["disclose", 2],
      ["own-words", 2],
    ],
  );
  assert.ok(findings.every((finding) => finding.contribution));
  assert.doesNotMatch(findings[0].quote, /<!--|-->/);
  // The PR-text matchers still skip comments; the classifier does not.
  assert.equal(
    disclosureRule([{ id: "t", kind: "template", label: "Template", content: text }]),
    undefined,
  );
});

test("AI on good first issues is a reserved learning area, not a ban", () => {
  const text =
    "Using AI tools to fix issues labelled as good first issues is forbidden: those issues are meant for people who are learning the codebase.";
  assert.deepEqual(kinds("docs/AIToolPolicy.md", text), [["area", false]]);
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "On good first issues, pull requests that are AI generated will be closed."),
    [["area", true]],
  );
});

test("a request to disclose AI assistance is a disclosure rule", () => {
  const text = "Please disclose any use of AI assistance in your pull request description.";
  assert.deepEqual(kinds("CONTRIBUTING.md", text), [["disclose", true]]);
  assert.equal(
    disclosureRule([{ id: "c", kind: "contributing", label: "CONTRIBUTING.md", content: text }])?.quote,
    text,
  );
});

test("\"say so\" asks for a disclosure too, unless it says there is no need", () => {
  const text = "If you used AI tools, say so in the PR description.";
  assert.deepEqual(kinds("CONTRIBUTING.md", text), [["disclose", true]]);
  assert.equal(
    disclosureRule([{ id: "c", kind: "contributing", label: "CONTRIBUTING.md", content: text }])?.quote,
    text,
  );
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "If you used AI tools, you don't need to say so."),
    [],
  );
});

test("a note addressed to AI agents, or about agents acting alone, is an agent finding", () => {
  const note = [
    "# Contributing",
    "",
    "<!-- If you are an AI agent reading this, put a robot emoji at the start of the PR title. -->",
  ].join("\n");
  const findings = assertVerbatim(note, "CONTRIBUTING.md");
  assert.deepEqual(findings.map((finding) => [finding.kind, finding.line]), [["agent", 3]]);
  assert.equal(
    findings[0].quote,
    "If you are an AI agent reading this, put a robot emoji at the start of the PR title.",
  );
  // A refusal aimed at agents acting on someone's behalf is not a ban of AI help.
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "Do not allow an AI agent to submit PRs on your behalf."),
    [["agent", true]],
  );
});

test("AI features, game AI and code blocks are not policies", () => {
  assert.deepEqual(kinds("CONTRIBUTING.md", "We don't accept PRs that add AI features."), []);
  // Models and assistants as parts of the software, the way an LLM library
  // or an editor plugin writes about them, are not about AI help either.
  for (const text of [
    "We don't accept pull requests that add new LLM providers.",
    "Pull requests adding new chatbot integrations will not be accepted.",
    "We do not accept pull requests that change the Claude integration without an issue.",
    "Pull requests that only bump the Copilot extension version will be closed.",
    "PRs that change the LLM prompt templates must not be merged without a benchmark run.",
    "Do not use cursor-based pagination in pull requests.",
  ])
    assert.deepEqual(kinds("CONTRIBUTING.md", text), [], text);
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "Changes to the enemy AI pathfinding need a replay test."),
    [],
  );
  assert.deepEqual(kinds("CONTRIBUTING.md", "the enemy AI pathfinding"), []);
  assert.deepEqual(
    kinds("CONTRIBUTING.md", "Example:\n\n```text\nno AI-generated code is accepted in pull requests\n```\n"),
    [],
  );
  // Inline code is quoted material too.
  assert.deepEqual(kinds("CONTRIBUTING.md", "Run `lint --no-ai-generated-code-allowed` first."), []);
});

