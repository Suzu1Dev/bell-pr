/**
 * What a project's own documents say about AI-assisted contributions and
 * how it wants to be contributed to, read deterministically from their
 * text. Every finding is a verbatim quote with its file and line, so the
 * person can read the rule where it is written; BELL never says a project
 * has "no policy" and is never an AI detector.
 *
 * Unlike the PR-text checks (`markdownProse`), the classifier keeps HTML
 * comments: pull request templates and contributing guides put rules there
 * (and notes addressed to AI agents). Fenced code is skipped.
 */
import { markdownProse, type DraftRuleQuote } from "./draft-checks.js";
import { aiDisclosureLine, type DraftSource } from "./drafts.js";
import type { PolicyFinding, PolicyKind } from "./contribution.js";

/** One line of a document outside fenced code, with its 1-based line number. */
export interface ProseLine {
  line: number;
  text: string;
}

/**
 * The lines of a Markdown (or plain-text) document that are prose: HTML
 * comments are kept as written, fenced code blocks (``` or ~~~) are left
 * out. Blank lines are kept, so paragraphs stay apart; a code block leaves
 * a gap in the line numbers.
 */
export function rawProse(text: string): ProseLine[] {
  const lines: ProseLine[] = [];
  let fence: { char: string; length: number } | undefined;
  text.split(/\r?\n/).forEach((raw, index) => {
    const marker = /^ {0,3}(`{3,}|~{3,})/.exec(raw);
    if (fence) {
      if (
        marker &&
        marker[1][0] === fence.char &&
        marker[1].length >= fence.length &&
        !raw.slice(marker[0].length).trim()
      )
        fence = undefined;
      return;
    }
    if (marker) {
      fence = { char: marker[1][0], length: marker[1].length };
      return;
    }
    lines.push({ line: index + 1, text: raw });
  });
  return lines;
}

const flags = "i";

/**
 * AI in the sense of help with writing a contribution: "AI-generated",
 * "AI-assisted", "generated by an LLM", AI tools, assistants and agents,
 * LLMs, generative AI, machine-generated text and the coding assistants by
 * name. Bare "AI" counts only next to tool, assist, generat, agent, written
 * or code, so "the enemy AI" or "AI features" are not about assistance.
 */
const assistanceTerms = [
  new RegExp(
    String.raw`\bAI[- ]?(?:generat\w*|assist\w*|written|authored|produced|tools?|tooling|agents?|code|coding|chatbots?)\b`,
    flags,
  ),
  new RegExp(
    String.raw`\b(?:generat\w*|written|produced|created|authored|assisted)\s+(?:by|with|using|through)\s+(?:an?\s+|the\s+)?(?:AI|LLMs?|large language models?|language models?|generative)\b`,
    flags,
  ),
  new RegExp(String.raw`\b(?:LLMs?|large language models?|chatbots?)\b`, flags),
  new RegExp(
    String.raw`\bgenerative\s+(?:AI|artificial intelligence|tools?|models?)\b`,
    flags,
  ),
  new RegExp(String.raw`\bmachine[- ]generated\b`, flags),
  new RegExp(
    String.raw`\bartificial intelligence(?:\s+\(AI\))?\s+(?:tools?|assistants?|agents?)\b`,
    flags,
  ),
  // Product names are matched as written, so "claude" or "codex" in other senses stay out.
  /\b(?:ChatGPT|Copilot|Claude|Codex|Gemini)\b/,
  /\bCursor(?=\s*(?:,|\bor\b|\band\b|\)|\/|\bAI\b|\bIDE\b|\bagents?\b))/,
  /\b(?:Copilot|ChatGPT|Claude|Codex),?\s+(?:or\s+|and\s+)?Cursor\b/,
];

/** Words that refuse something. */
const prohibition = new RegExp(
  [
    String.raw`\b(?:do|does|will|shall|should|must|may|can)\s*(?:not|n't)\s+(?:\w+\s+){0,3}?(?:accept|allow|permit|use|submit|merge|review|consider|welcome|take|contribut)\w*`,
    String.raw`\b(?:won't|cannot|can't|never)\s+(?:\w+\s+){0,3}?(?:accept|allow|permit|use|submit|merge|review|consider|welcome|take|contribut)\w*`,
    String.raw`\bnot\s+(?:be\s+)?(?:accepted|allowed|permitted|welcome|tolerated|merged|reviewed|considered)\b`,
    String.raw`\b(?:prohibited|forbidden|banned|disallowed|unacceptable|declined?)\b`,
    String.raw`\bno\s+(?:AI|LLM|machine)[\w-]*`,
    String.raw`\b(?:will|shall|may)\s+be\s+(?:closed|rejected|refused|declined)\b`,
    String.raw`\bzero[- ]tolerance\b`,
  ].join("|"),
  flags,
);

/** Issues set aside for people who are learning. */
const learningIssues = new RegExp(
  String.raw`\bgood[- ]first[- ]issues?\b|\bfirst[- ]timers?(?:[- ]only)?\b|\b(?:beginner(?:[- ]friendly)?|newcomer|starter|easy)\s+issues?\b`,
  flags,
);
const reservation = new RegExp(
  String.raw`\b(?:reserved|meant|intended|kept)\s+for\b|\bare\s+for\s+(?:human\s+|new\s+)?(?:contributors|newcomers|people|humans)\b`,
  flags,
);

/** Text addressed to AI agents themselves. */
const addressedToAgents = new RegExp(
  [
    String.raw`\b(?:if\s+)?you(?:'re|\s+are)\s+(?:an?\s+)?(?:AI|LLM)(?:[- ]based)?\s+(?:coding\s+)?(?:agents?|assistants?|models?|tools?|bots?)\b`,
    String.raw`\b(?:if\s+)?you(?:'re|\s+are)\s+(?:an?\s+)?(?:LLM|large language model|language model|coding agent|autonomous agent)\b`,
    String.raw`^\W*(?:note|instructions?|message|attention|dear)\s*(?:to|for)?\s*(?:all\s+|any\s+)?(?:AI|LLM)(?:[- ]based)?\s+(?:coding\s+)?(?:agents?|assistants?|models?|tools?|bots?)\b`,
    String.raw`^\W*(?:AI|LLM)\s+(?:coding\s+)?(?:agents?|assistants?)\s*:`,
    String.raw`\b(?:AI|LLM|coding)\s+agents?\s+(?:must|should|need\s+to|are\s+required\s+to|may\s+not|are\s+not\s+allowed)\b`,
  ].join("|"),
  flags,
);
/** Agents acting on the forge by themselves, which a person's own PR is not. */
const autonomousAction = new RegExp(
  String.raw`\b(?:on\s+(?:your|their|someone's)\s+behalf|autonomous\w*|directly\s+interact\w*|without\s+(?:a\s+)?human|take\s+action|acting\s+on)\b`,
  flags,
);

/** Contributors must be able to explain their changes. */
const understandingRule = new RegExp(
  String.raw`\b(?:must|should|need(?:s)?\s+to|ha(?:ve|s)\s+to|(?:are|is)\s+expected\s+to|(?:are|is)\s+required\s+to|be\s+able\s+to)\s+(?:\w+\s+){0,3}?(?:explain|understand|answer\s+questions?\s+about|defend|justify)\s+(?:\w+\s+){0,2}?(?:changes?|code|work|contributions?|patch(?:es)?|pull\s+requests?|PRs?|submissions?|diffs?)\b(?!\s+(?:of\s+conduct|style|base|review\s+guidelines))`,
  flags,
);

/** Descriptions written by the contributor, not generated. */
const ownWordsRule = new RegExp(
  [
    String.raw`\b(?:in|with|using)\s+(?:your|their|the\s+(?:contributor|author)'s)\s+own\s+(?:human\s+)?(?:words|voice)\b`,
    String.raw`\bown\s+human\s+voice\b`,
    String.raw`\bwrite\s+(?:the|your|a|this)\s+(?:PR\s+|pull\s+request\s+)?description\s+(?:yourself|by\s+hand)\b`,
  ].join("|"),
  flags,
);

/** An issue (or a claim on one) before the work starts. */
const issueFirstRule = new RegExp(
  [
    String.raw`\b(?:open|file|create|raise|start|claim)(?:\s+or\s+\w+)?\s+(?:an?\s+|the\s+)?(?:new\s+)?issue\b[^.!?]{0,80}?\b(?:before|first|prior\s+to)\b`,
    String.raw`\bbefore\b[^.!?]{0,80}?\b(?:open|file|create|raise)(?:\s+or\s+\w+)?\s+(?:an?\s+)?issue\b`,
    String.raw`\b(?:discuss|propose)\b[^.!?]{0,60}?\b(?:in|on)\s+(?:an?|the)\s+issue\b[^.!?]{0,40}?\b(?:first|before)\b`,
    String.raw`\bcomment\s+on\s+the\s+issue\b[^.!?]{0,60}?\bbefore\b`,
  ].join("|"),
  flags,
);

/** A sentence that is about a contribution: a PR, a patch, a commit or submitted code. */
const contributionContext = new RegExp(
  String.raw`\b(?:PRs?|pull[- ]requests?|merge\s+requests?|patch(?:es|sets?)?|contribut\w*|commits?|submi(?:t|ts|tted|tting|ssions?))\b`,
  flags,
);

/** How close (in characters) an AI term and the rule's words must be. */
const proximity = 120;
const maxQuote = 300;

interface Span {
  start: number;
  end: number;
}

/** One paragraph or list item, its lines joined, with where each line starts. */
interface Block {
  text: string;
  starts: { offset: number; line: number }[];
}

/** Paragraphs, list items and headings each form a block; blank lines and code end one. */
function blocks(prose: ProseLine[]): Block[] {
  const result: Block[] = [];
  let current: Block | undefined;
  let previous = 0;
  for (const { line, text } of prose) {
    const blank = !text.trim();
    const starts =
      /^\s{0,3}#{1,6}\s/.test(text) ||
      /^\s*(?:[-*+]|\d{1,9}[.)])\s+/.test(text) ||
      line !== previous + 1;
    previous = line;
    if (blank || starts || !current) {
      if (current) result.push(current);
      current = blank ? undefined : { text: "", starts: [] };
      if (blank) continue;
    }
    // A continuation line's indent is layout, not part of the sentence.
    const piece = current!.text ? text.trimStart() : text;
    if (current!.text) current!.text += " ";
    current!.starts.push({ offset: current!.text.length, line });
    current!.text += piece;
    // A heading is a block of its own.
    if (/^\s{0,3}#{1,6}\s/.test(text)) {
      result.push(current!);
      current = undefined;
    }
  }
  if (current) result.push(current);
  return result;
}

function lineAt(block: Block, offset: number) {
  let line = block.starts[0].line;
  for (const start of block.starts) if (start.offset <= offset) line = start.line;
  return line;
}

/** Text to search: inline code and comment delimiters blanked, positions kept. */
function searchable(text: string) {
  return text
    .replace(/`[^`]*`/g, (code) => " ".repeat(code.length))
    .replace(/<!--|-->/g, (marker) => " ".repeat(marker.length));
}

/**
 * The sentence around a span: from the end of the sentence before it to
 * the end of the one it ends in. An HTML comment's delimiters end a
 * sentence too, so a rule in a comment is quoted without the text after it.
 */
function sentenceAround(text: string, span: Span): Span {
  const boundaries = [
    ...[...text.matchAll(/[.!?](?=\s|$)/g)].map((match) => [match.index + 1, match.index + 1]),
    ...[...text.matchAll(/<!--|-->/g)].map((match) => [
      match.index,
      match.index + match[0].length,
    ]),
  ].sort((a, b) => a[0] - b[0]);
  let start = 0;
  let end = text.length;
  for (const [before, after] of boundaries) {
    if (after <= span.start) start = after;
    else if (before >= span.end) {
      end = before;
      break;
    }
  }
  return { start, end };
}

/** A verbatim quote of at most 300 characters, without Markdown markers at its edges. */
function quoteOf(text: string, sentence: Span, match: Span) {
  let { start, end } = sentence;
  if (end - start > maxQuote) {
    const room = Math.max(0, maxQuote - (match.end - match.start));
    start = Math.max(sentence.start, match.start - Math.floor(room / 2));
    end = Math.min(sentence.end, start + maxQuote);
    start = Math.max(sentence.start, end - maxQuote);
  }
  let quote = text.slice(start, end);
  let offset = start;
  const lead =
    /^(?:\s|<!--|>|#{1,6}\s|[-*+]\s|\d{1,9}[.)]\s|\[[ xX]\]\s|\*\*|__)+/.exec(quote);
  if (lead) {
    quote = quote.slice(lead[0].length);
    offset += lead[0].length;
  }
  quote = quote.replace(/(?:\s|-->|\*\*|__)+$/, "");
  return { quote: quote.slice(0, maxQuote), offset };
}

function allMatches(pattern: RegExp, text: string): Span[] {
  const global = new RegExp(
    pattern.source,
    pattern.flags.includes("g") ? pattern.flags : `${pattern.flags}g`,
  );
  return [...text.matchAll(global)].map((match) => ({
    start: match.index,
    end: match.index + match[0].length,
  }));
}

const gap = (a: Span, b: Span) => Math.max(0, b.start - a.end, a.start - b.end);

/**
 * Each rule phrase with the nearest AI-assistance term, when one is close
 * enough to make them one rule; the span covers both.
 */
function nearAssistance(text: string, rule: RegExp) {
  const terms = assistanceTerms.flatMap((term) => allMatches(term, text));
  const pairs: { phrase: Span; span: Span; term: Span }[] = [];
  for (const phrase of allMatches(rule, text)) {
    const term = terms
      .filter((candidate) => gap(candidate, phrase) <= proximity)
      .sort((a, b) => gap(a, phrase) - gap(b, phrase))[0];
    if (term)
      pairs.push({
        phrase,
        term,
        span: {
          start: Math.min(term.start, phrase.start),
          end: Math.max(term.end, phrase.end),
        },
      });
  }
  return pairs;
}

/**
 * The rules a project document states, by kind, each with a verbatim
 * quote (300 characters or fewer) and its 1-based line:
 * - `ban`: AI-assisted contributions refused. `contribution` is true when
 *   the same sentence names a PR, patch, contribution, commit or submitted
 *   code; only then does it block publishing.
 * - `disclose`: AI assistance must be disclosed (see `disclosureRule`).
 * - `understand`: contributors must be able to explain their changes.
 * - `area`: learning issues (good first issues and the like) are reserved
 *   for people, without AI.
 * - `agent`: text addressed to AI agents, or about agents acting by
 *   themselves; the person decides whether it applies.
 * - `own-words`: descriptions in the contributor's own words.
 * - `issue-first`: an issue before the work.
 *
 * The AI kinds need an AI term in an assistance sense within about 120
 * characters of the rule's words; the others are contribution rules that
 * need no AI term.
 */
export function classifyPolicy(path: string, text: string): PolicyFinding[] {
  const findings: PolicyFinding[] = [];
  const seen = new Set<string>();
  const add = (kind: PolicyKind, block: Block, search: string, match: Span) => {
    const sentence = sentenceAround(block.text, match);
    const { quote, offset } = quoteOf(block.text, sentence, match);
    if (!quote.trim()) return;
    const key = `${kind}:${lineAt(block, offset)}:${quote}`;
    if (seen.has(key)) return;
    seen.add(key);
    findings.push({
      kind,
      path,
      line: lineAt(block, offset),
      quote,
      contribution: contributionContext.test(
        search.slice(sentence.start, sentence.end),
      ),
    });
  };
  for (const block of blocks(rawProse(text))) {
    const search = searchable(block.text);
    // One AI finding per sentence: a reserved learning area wins over a ban.
    const decided = new Set<number>();
    const sentenceOf = (span: Span) => sentenceAround(block.text, span);
    for (const { phrase, span } of nearAssistance(search, learningIssues)) {
      const sentence = sentenceOf(phrase);
      const words = search.slice(sentence.start, sentence.end);
      if (decided.has(sentence.start)) continue;
      if (prohibition.test(words) || reservation.test(words)) {
        add("area", block, search, span);
        decided.add(sentence.start);
      }
    }
    for (const { phrase, span, term } of nearAssistance(search, prohibition)) {
      const sentence = sentenceOf(phrase);
      if (decided.has(sentence.start)) continue;
      decided.add(sentence.start);
      const words = search.slice(sentence.start, sentence.end);
      const agentTerm = /agent|bot/i.test(search.slice(term.start, term.end));
      add(
        agentTerm && autonomousAction.test(words) ? "agent" : "ban",
        block,
        search,
        span,
      );
    }
    for (const match of allMatches(addressedToAgents, search))
      add("agent", block, search, match);
    for (const sentence of splitSentences(block.text))
      if (asksForDisclosure(search.slice(sentence.start, sentence.end)))
        add("disclose", block, search, sentence);
    for (const [kind, rule] of [
      ["understand", understandingRule],
      ["own-words", ownWordsRule],
      ["issue-first", issueFirstRule],
    ] as const)
      for (const match of allMatches(rule, search)) add(kind, block, search, match);
  }
  return findings
    .sort((a, b) => a.line - b.line)
    .slice(0, 30);
}

/** The sentences of a text, split after . ! or ? and at comment delimiters. */
function splitSentences(text: string): Span[] {
  const spans: Span[] = [];
  let at = 0;
  while (at < text.length) {
    const span = sentenceAround(text, { start: at, end: at + 1 });
    spans.push({ start: Math.max(span.start, at), end: span.end });
    at = Math.max(span.end, at + 1);
  }
  return spans.filter((span) =>
    text.slice(span.start, span.end).replace(/<!--|-->/g, "").trim(),
  );
}

const aiTerm =
  "(?:AI|LLMs?|large language models?|generative|gen[- ]?AI|artificial intelligence|machine[- ]generated|Copilot|ChatGPT|Claude|Codex)\\b";
const discloseVerb =
  "(?:disclos\\w*|declar\\w*|mention|indicate|state|tell us|let us know)";
const disclosedPassive =
  "(?:disclosed|declared|mentioned|indicated|stated|labell?ed|marked|flagged|noted)";

/** Lines that ask for a disclosure, in either word order. */
const disclosurePattern = new RegExp(
  [
    // "Please disclose any use of AI tools", "tell us if you used an LLM".
    `\\b${discloseVerb}\\b[^.\\n]{0,80}\\b${aiTerm}`,
    // "AI-assisted contributions must be disclosed", "LLM use should be noted",
    // "if you use AI tools, you must disclose it".
    `\\b${aiTerm}[^.\\n]{0,80}\\b(?:must|should|please|needs? to|has to|have to|is required to|are required to|shall)\\b(?:[^.\\n]{0,40}\\b${disclosedPassive}\\b|\\s+(?:\\w+\\s+)?${discloseVerb}\\b)`,
  ].join("|"),
  "i",
);

/**
 * The patterns above also fit lines about an AI feature ("state whether
 * the AI module changed", "let us know if you need help with the AI
 * backend"), so a line counts only when it is about using AI to make the
 * contribution.
 */
const aiUse =
  /\b(?:us(?:e|es|ed|ing|age)|assist\w*|generated|wr(?:ote|itten)|authored|produced)\b/i;

/** A template heading or checkbox: "## AI disclosure", "[ ] AI usage disclosed". */
const disclosureHeading =
  /\b(?:AI|LLM)[- ](?:assistance |usage |use )?disclos\w*/i;

/** "Do not mention AI" and the like are not disclosure rules. */
const negated =
  /\b(?:do not|don't|never|no need to|not required to)\s+(?:\w+\s+){0,2}(?:disclos|declar|mention|state|indicate)/i;

/** Whether one line of prose asks contributors to disclose AI assistance. */
const asksForDisclosure = (prose: string) =>
  !negated.test(prose) &&
  (disclosureHeading.test(prose) ||
    (disclosurePattern.test(prose) && aiUse.test(prose)));

/**
 * The first contributing-guide or template line that asks for an
 * AI-assistance disclosure, with its source; code blocks and comments are
 * ignored, like the other rule quotes.
 */
export function disclosureRule(
  sources: readonly DraftSource[],
): DraftRuleQuote | undefined {
  for (const source of sources) {
    if (source.kind !== "contributing" && source.kind !== "template") continue;
    const lines = source.content.split("\n");
    const index = markdownProse(source.content).findIndex(asksForDisclosure);
    if (index < 0) continue;
    return {
      sourceId: source.id,
      label: source.label,
      quote: lines[index]
        .replace(/\*\*|__/g, "")
        .trim()
        .replace(/^[-*>#\s]+/, "")
        .replace(/^\[[ xX]\]\s*/, "")
        .slice(0, 200),
    };
  }
  return undefined;
}

/** A trailer naming the tool that helped, as kernel, LLVM and ASF policies ask. */
const toolTrailer = /^\s*(?:Assisted|Generated)-by:\s*\S/im;
const disclosureTool = [
  ...assistanceTerms,
  new RegExp(
    String.raw`\b(?:us(?:e|ed|ing)|use\s+of|with|via|by|from)\s+(?:an?\s+)?(?:AI|LLMs?)\b|\bAI[- ](?:help|support)\b`,
    flags,
  ),
];
const disclosureVerb = /\b(?:us(?:e|ed|es|ing)|assist\w*|generat\w*)\b/i;

/**
 * Whether the PR text says that AI helped: BELL's own disclosure line, an
 * `Assisted-by:` or `Generated-by:` trailer in the description or the
 * commit message, or a visible sentence of the description that names an
 * AI tool together with used, assisted or generated. Text in comments or
 * code does not count: maintainers would not see it.
 */
export function hasAiDisclosure(body: string, commitMessage = "") {
  if (body.includes(aiDisclosureLine)) return true;
  if (toolTrailer.test(commitMessage)) return true;
  const lines = markdownProse(body);
  if (lines.some((line) => toolTrailer.test(line))) return true;
  const visible = lines.join(" ");
  return splitSentences(visible).some(({ start, end }) => {
    const sentence = visible.slice(start, end);
    return (
      disclosureVerb.test(sentence) &&
      disclosureTool.some((term) => term.test(sentence))
    );
  });
}
