/** How close (in characters) an AI term and the rule's words must be. */
const proximity = 120;
const maxQuote = 300;

interface Span {
  start: number;
  end: number;
}

/** One paragraph or list item, its lines joined, with where each line starts. */
interface Block {
  text: string;
  starts: { offset: number; line: number }[];
}

/** Paragraphs, list items and headings each form a block; blank lines and code end one. */
function blocks(prose: ProseLine[]): Block[] {
  const result: Block[] = [];
  let current: Block | undefined;
  let previous = 0;
  for (const { line, text } of prose) {
    const blank = !text.trim();
    const starts =
      /^\s{0,3}#{1,6}\s/.test(text) ||
      /^\s*(?:[-*+]|\d{1,9}[.)])\s+/.test(text) ||
      line !== previous + 1;
    previous = line;
    if (blank || starts || !current) {
      if (current) result.push(current);
      current = blank ? undefined : { text: "", starts: [] };
      if (blank) continue;
    }
    // A continuation line's indent is layout, not part of the sentence.
    const piece = current!.text ? text.trimStart() : text;
    if (current!.text) current!.text += " ";
    current!.starts.push({ offset: current!.text.length, line });
    current!.text += piece;
    // A heading is a block of its own.
    if (/^\s{0,3}#{1,6}\s/.test(text)) {
      result.push(current!);
      current = undefined;
    }
  }
  if (current) result.push(current);
  return result;
}

function lineAt(block: Block, offset: number) {
  let line = block.starts[0].line;
  for (const start of block.starts) if (start.offset <= offset) line = start.line;
  return line;
}

/** Text to search: inline code and comment delimiters blanked, positions kept. */
function searchable(text: string) {
  return text
    .replace(/`[^`]*`/g, (code) => " ".repeat(code.length))
    .replace(/<!--|-->/g, (marker) => " ".repeat(marker.length));
}

/**
 * The sentence around a span: from the end of the sentence before it to
 * the end of the one it ends in. An HTML comment's delimiters end a
 * sentence too, so a rule in a comment is quoted without the text after it.
 */
function sentenceAround(text: string, span: Span): Span {
  const boundaries = [
    ...[...text.matchAll(/[.!?](?=\s|$)/g)].map((match) => [match.index + 1, match.index + 1]),
    ...[...text.matchAll(/<!--|-->/g)].map((match) => [
      match.index,
      match.index + match[0].length,
    ]),
  ].sort((a, b) => a[0] - b[0]);
  let start = 0;
  let end = text.length;
  for (const [before, after] of boundaries) {
    if (after <= span.start) start = after;
    else if (before >= span.end) {
      end = before;
      break;
    }
  }
  return { start, end };
}

/** A verbatim quote of at most 300 characters, without Markdown markers at its edges. */
function quoteOf(text: string, sentence: Span, match: Span) {
  let { start, end } = sentence;
  if (end - start > maxQuote) {
    const room = Math.max(0, maxQuote - (match.end - match.start));
    start = Math.max(sentence.start, match.start - Math.floor(room / 2));
    end = Math.min(sentence.end, start + maxQuote);
    start = Math.max(sentence.start, end - maxQuote);
  }
  let quote = text.slice(start, end);
  let offset = start;
  const lead =
    /^(?:\s|<!--|>|#{1,6}\s|[-*+]\s|\d{1,9}[.)]\s|\[[ xX]\]\s|\*\*|__)+/.exec(quote);
  if (lead) {
    quote = quote.slice(lead[0].length);
    offset += lead[0].length;
  }
  quote = quote.replace(/(?:\s|-->|\*\*|__)+$/, "");
  return { quote: quote.slice(0, maxQuote), offset };
}

function allMatches(pattern: RegExp, text: string): Span[] {
  const global = new RegExp(
    pattern.source,
    pattern.flags.includes("g") ? pattern.flags : `${pattern.flags}g`,
  );
  return [...text.matchAll(global)].map((match) => ({
    start: match.index,
    end: match.index + match[0].length,
  }));
}

const gap = (a: Span, b: Span) => Math.max(0, b.start - a.end, a.start - b.end);

/**
 * Each rule phrase with the nearest AI-assistance term, when one is close
 * enough and in the same sentence to make them one rule; the span covers
 * both. A refusal in one sentence and an AI term in the next ("We do not
 * accept typo-only PRs. AI tools can help you find bugs.") are two things.
 */
function nearAssistance(
  text: string,
  rule: RegExp,
  sentenceOf: (span: Span) => Span,
) {
  const terms = assistanceSpans(text);
  const pairs: { phrase: Span; span: Span; term: Span }[] = [];
  for (const phrase of allMatches(rule, text)) {
    const sentence = sentenceOf(phrase);
    const term = terms
      .filter(
        (candidate) =>
          candidate.start >= sentence.start &&
          candidate.end <= sentence.end &&
          gap(candidate, phrase) <= proximity,
      )
      .sort((a, b) => gap(a, phrase) - gap(b, phrase))[0];
    if (term)
      pairs.push({
        phrase,
        term,
        span: {
          start: Math.min(term.start, phrase.start),
          end: Math.max(term.end, phrase.end),
        },
      });
  }
  return pairs;
}

/**
 * The rules a project document states, by kind, each with a verbatim
 * quote (300 characters or fewer) and its 1-based line:
 * - `ban`: AI-assisted contributions refused. `contribution` is true when
 *   the same sentence names a PR, patch, contribution, commit or submitted
 *   code; only then does it block publishing.
 * - `disclose`: AI assistance must be disclosed (see `disclosureRule`).
 * - `understand`: contributors must be able to explain their changes.
 * - `area`: learning issues (good first issues and the like) are reserved
 *   for people, without AI.
 * - `agent`: text addressed to AI agents, or about agents acting by
 *   themselves; the person decides whether it applies.
 * - `own-words`: descriptions in the contributor's own words.
 * - `issue-first`: an issue before the work.
 *
 * The AI kinds need an AI term in an assistance sense within about 120
 * characters of the rule's words, in the same sentence; the others are
 * contribution rules that need no AI term. A refusal in a sentence that
 * lets contributors use AI ("You may use AI tools, but …") is ambiguous:
 * a ban without contribution context, which never blocks.
 */
export function classifyPolicy(path: string, text: string): PolicyFinding[] {
  const findings: PolicyFinding[] = [];
  const seen = new Set<string>();
  const add = (
    kind: PolicyKind,
    block: Block,
    search: string,
    match: Span,
    ambiguous = false,
  ) => {
    const sentence = sentenceAround(block.text, match);
    const { quote, offset } = quoteOf(block.text, sentence, match);
    if (!quote.trim()) return;
    const key = `${kind}:${lineAt(block, offset)}:${quote}`;
    if (seen.has(key)) return;
    seen.add(key);
    findings.push({
      kind,
      path,
      line: lineAt(block, offset),
      quote,
      contribution:
        !ambiguous &&
        contributionContext.test(search.slice(sentence.start, sentence.end)),
    });
  };
  for (const block of blocks(rawProse(text))) {
    const search = searchable(block.text);
    // One AI finding per sentence: a reserved learning area wins over a ban.
    const decided = new Set<number>();
    const sentenceOf = (span: Span) => sentenceAround(block.text, span);
    for (const { phrase, span } of nearAssistance(search, learningIssues, sentenceOf)) {
      const sentence = sentenceOf(phrase);
      const words = search.slice(sentence.start, sentence.end);
      if (decided.has(sentence.start)) continue;
      if (prohibition.test(words) || reservation.test(words)) {
        add("area", block, search, span);
        decided.add(sentence.start);
      }
    }
    for (const { phrase, span, term } of nearAssistance(search, prohibition, sentenceOf)) {
      const sentence = sentenceOf(phrase);
      if (decided.has(sentence.start)) continue;
      decided.add(sentence.start);
      const words = search.slice(sentence.start, sentence.end);
      const agentTerm = /agent|bot/i.test(search.slice(term.start, term.end));
      // "You may use AI tools, but …": the AI use itself is allowed.
      const permitted = allMatches(aiPermission, words).some(
        (match) =>
          sentence.start + match.end <= term.start &&
          term.start - (sentence.start + match.end) <= 20,
      );
      // "… unless you have reviewed every line": a rule about how AI is used.
      const conditional =
        conductCondition.test(words) && !maintainerPermission.test(words);
      // "Write the PR description and comments without AI": a rule about
      // the conversation, not the change; for the description it is the
      // project's own-words rule.
      const aboutConversation =
        conversation.test(words) && !changeObject.test(words);
      if (agentTerm && autonomousAction.test(words))
        add("agent", block, search, span);
      else if (aboutConversation && /\bdescriptions?\b/i.test(words))
        add("own-words", block, search, span);
      else
        add("ban", block, search, span, permitted || conditional || aboutConversation);
    }
    for (const match of allMatches(addressedToAgents, search))
      add("agent", block, search, match);
    for (const sentence of splitSentences(block.text))
      if (asksForDisclosure(search.slice(sentence.start, sentence.end)))
        add("disclose", block, search, sentence);
    for (const [kind, rule] of [
      ["understand", understandingRule],
      ["own-words", ownWordsRule],
      ["issue-first", issueFirstRule],
    ] as const)
      for (const match of allMatches(rule, search)) add(kind, block, search, match);
  }
  return findings
    .sort((a, b) => a.line - b.line)
    .slice(0, 30);
}

/** The sentences of a text, split after . ! or ? and at comment delimiters. */
function splitSentences(text: string): Span[] {
  const spans: Span[] = [];
  let at = 0;
  while (at < text.length) {
    const span = sentenceAround(text, { start: at, end: at + 1 });
    spans.push({ start: Math.max(span.start, at), end: span.end });
    at = Math.max(span.end, at + 1);
  }
  return spans.filter((span) =>
    text.slice(span.start, span.end).replace(/<!--|-->/g, "").trim(),
  );
}

