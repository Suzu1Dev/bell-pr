/** How close (in characters) an AI term and the rule's words must be. */
const proximity = 120;
const maxQuote = 300;

interface Span {
  start: number;
  end: number;
}

/** One paragraph or list item, its lines joined, with where each line starts. */
interface Block {
  text: string;
  starts: { offset: number; line: number }[];
}

/** Paragraphs, list items and headings each form a block; blank lines and code end one. */
function blocks(prose: ProseLine[]): Block[] {
  const result: Block[] = [];
  let current: Block | undefined;
  let previous = 0;
  for (const { line, text } of prose) {
    const blank = !text.trim();
    const starts =
      /^\s{0,3}#{1,6}\s/.test(text) ||
      /^\s*(?:[-*+]|\d{1,9}[.)])\s+/.test(text) ||
      line !== previous + 1;
    previous = line;
    if (blank || starts || !current) {
      if (current) result.push(current);
      current = blank ? undefined : { text: "", starts: [] };
      if (blank) continue;
    }
    // A continuation line's indent is layout, not part of the sentence.
    const piece = current!.text ? text.trimStart() : text;
    if (current!.text) current!.text += " ";
    current!.starts.push({ offset: current!.text.length, line });
    current!.text += piece;
    // A heading is a block of its own.
    if (/^\s{0,3}#{1,6}\s/.test(text)) {
      result.push(current!);
      current = undefined;
    }
  }
  if (current) result.push(current);
  return result;
}

/** The line of a block an offset is on: that of the last line start at or before it. */
function lineAt(block: Block, offset: number) {
  const after = firstIndex(block.starts.length, (index) => block.starts[index].offset > offset);
  return block.starts[Math.max(0, after - 1)].line;
}

const blank = (text: string) => " ".repeat(text.length);

/** `text` at `offset` inside `whole`, everything else in `whole` blanked. */
const keepOnly = (whole: string, offset: number, text: string) =>
  blank(whole.slice(0, offset)) + text + blank(whole.slice(offset + text.length));

/**
 * Inline code a policy writes a label or a trailer in ("`good first
 * issue`", "``Assisted-by:``"): words the reader is meant to read, not code.
 * The words are checked before the label is looked for, so a long code
 * span is read once.
 */
const quotedWords = /^(?:\s*(?:Assisted|Generated)-by:?\s*|(?=[\w\s'’-]*$)[\w\s'’-]*\bgood[- ]first[- ]issues?\b[\w\s'’-]*)$/i;

/**
 * Text to search, positions kept: inline code and comment delimiters
 * blanked, emphasis markers too; what a reStructuredText role or link shows
 * (":ref:`AI generated <target>`", "`text <url>`_") stays readable.
 * Typographic apostrophes and hyphens read as typed ones ("don’t",
 * "AI‑generated"), one character for one, so a rule written with them is
 * found; quotes keep the file's own characters. A role's or a link's text
 * is trimmed after it is matched, not by the pattern, which would read a
 * run of spaces again from each space.
 */
function searchable(text: string) {
  return text
    .replace(/[\u2018\u2019\u02bc\u2032]/g, "'")
    .replace(/[\u2010\u2011]/g, "-")
    .replace(
      /:[\w.+-]+:`([^`]*)`|`([^`<]*)<[^`>]*>`_{1,2}/g,
      (whole: string, role: string | undefined, link: string | undefined) => {
        const target = role === undefined ? undefined : /<[^<>]*>\s*$/.exec(role);
        const shown = role === undefined ? link!.trimEnd() : target ? role.slice(0, target.index).trimEnd() : role;
        return keepOnly(whole, whole.indexOf("`") + 1, shown);
      },
    )
    .replace(/`([^`]*)`/g, (code, inside: string) =>
      quotedWords.test(inside) ? keepOnly(code, 1, inside) : blank(code),
    )
    .replace(markdownLink, (whole: string, label: string) => keepOnly(whole, whole.indexOf("[") + 1, label))
    .replace(inlineTag, blank)
    .replace(/&(?:nbsp|#160|#x[aA]0);/g, (entity: string) => ` ${blank(entity.slice(1))}`)
    .replace(/&(?:#8208|#8209|#x201[01]|#45|hyphen|dash);/gi, (entity: string) => `-${blank(entity.slice(1))}`)
    .replace(/<!--|-->/g, blank)
    .replace(/\*\*|__|(?<![\w*])\*(?=\w)|(?<=\w)\*(?![\w*])|(?<![\w_])_(?=\w)|(?<=\w)_(?![\w_])/g, blank);
}

/**
 * A Markdown link or image, inline or by reference: what it shows is read,
 * not where it leads. Its text holds no "[" (a run of them is read once).
 */
const markdownLink =
  /!?\[([^[\]\n]*)\](?:\((?:[^()\s]|\([^()\s]*\))*(?:\s+(?:"[^"]*"|'[^']*'))?\)|\[[^\]\n]*\])/g;
/** Inline HTML a policy writes words in ("<b>AI-generated</b>", "<em>not</em>"), and line breaks. */
const inlineTag =
  /<\/?(?:a|abbr|b|big|cite|code|del|em|font|i|ins|kbd|mark|q|s|small|span|strike|strong|sub|sup|tt|u)\b[^<>]*>|<br\s*\/?>/gi;

/**
 * Where sentences end: after . ! or ? (and any closing bracket, quote or
 * emphasis marker) before a space or the end, never inside "e.g.", "i.e."
 * or "etc." ("(Copilot, ChatGPT, etc.) are not allowed"); and at an HTML
 * comment's delimiters, which never touch the punctuation.
 */
const sentenceEnd = /<!--|-->|(?<!\b(?:e\.g|i\.e|etc))[.!?]["'’”)\]*_]*(?=\s|$)/gi;

/**
 * Where the sentences of `text` end (`sentenceEnd`), in reading order, as
 * [before, after]: a sentence ends after its punctuation, and before a
 * comment's delimiter.
 */
const sentenceEnds = (text: string) =>
  [...text.matchAll(sentenceEnd)].map((match) => [
    match.index + ("<-".includes(match[0][0]) ? 0 : 1),
    match.index + match[0].length,
  ]);

/** The first index below `length` where `test` holds, for a test that holds from some index on. */
function firstIndex(length: number, test: (index: number) => boolean) {
  let low = 0;
  let high = length;
  while (low < high) {
    const middle = (low + high) >> 1;
    if (test(middle)) high = middle;
    else low = middle + 1;
  }
  return low;
}

/**
 * The sentence around a span: from the end of the sentence before it to
 * the end of the one it ends in. An HTML comment's delimiters end a
 * sentence too, so a rule in a comment is quoted without the text after it.
 * `ends` are the text's (`sentenceEnds`): in order and never overlapping,
 * so both are found by halving.
 */
function sentenceAround(text: string, ends: number[][], span: Span): Span {
  const next = firstIndex(ends.length, (index) => ends[index][0] >= span.end);
  const previous = Math.min(next, firstIndex(ends.length, (index) => ends[index][1] > span.start)) - 1;
  return { start: previous < 0 ? 0 : ends[previous][1], end: next < ends.length ? ends[next][0] : text.length };
}

/** A verbatim quote of at most 300 characters, without Markdown markers at its edges. */
function quoteOf(text: string, sentence: Span, match: Span) {
  let { start, end } = sentence;
  if (end - start > maxQuote) {
    const room = Math.max(0, maxQuote - (match.end - match.start));
    start = Math.max(sentence.start, match.start - Math.floor(room / 2));
    end = Math.min(sentence.end, start + maxQuote);
    start = Math.max(sentence.start, end - maxQuote);
  }
  let quote = text.slice(start, end);
  let offset = start;
  const lead =
    /^(?:\s|<!--|>|#{1,6}\s|[-*+]\s|\d{1,9}[.)]\s|\[[ xX]\]\s|\*\*|__)+/.exec(quote);
  if (lead) {
    quote = quote.slice(lead[0].length);
    offset += lead[0].length;
  }
  quote = quote.replace(/(?:\s|-->|\*\*|__)+$/, "");
  return { quote: quote.slice(0, maxQuote), offset };
}

function allMatches(pattern: RegExp, text: string): Span[] {
  const global = new RegExp(
    pattern.source,
    pattern.flags.includes("g") ? pattern.flags : `${pattern.flags}g`,
  );
  return [...text.matchAll(global)].map((match) => ({
    start: match.index,
    end: match.index + match[0].length,
  }));
}

/** Each pattern's global copy, made once: a copy made per call was most of the cost of a document of many short blocks. */
const globalCopies = new WeakMap<RegExp, RegExp>();

/**
 * allMatches for the classifier, which asks it thousands of times for a
 * document of many short blocks: the same spans, each pattern's global
 * copy made once (no pattern here reads Unicode code points).
 */
function cachedMatches(pattern: RegExp, text: string): Span[] {
  const global = globalCopies.get(pattern) ?? new RegExp(pattern.source, `${pattern.flags.replace("g", "")}g`);
  globalCopies.set(pattern, global);
  const spans: Span[] = [];
  global.lastIndex = 0;
  for (let match = global.exec(text); match; match = global.exec(text)) {
    spans.push({ start: match.index, end: match.index + match[0].length });
    // As matchAll does, an empty match moves on by one character.
    if (!match[0]) global.lastIndex = match.index + 1;
  }
  return spans;
}

const gap = (a: Span, b: Span) => Math.max(0, b.start - a.end, a.start - b.end);

/**
 * "No LLMs for patches / pull requests.", "No AI for issues.": a model
 * named for what it must not be used on is AI help too (DESIGN v1.2 F14,
 * Zig's README). The classifier's rules only; disclosure checks don't use it.
 */
const noAiFor = new RegExp(
  String.raw`\bno\s+${aiNoun}\s+for\s+(?:patch(?:es)?|pull\s+requests?|PRs?|issues?|comments?|contributions?)\b`,
  "i",
);
refusalTerms.push(noAiFor);
/**
 * A compound split by blanked markup: "AI-**generated**", "**AI**-generated"
 * or "AI&nbsp;tools" read "AI-  generated", "  AI  -generated", "AI      tools".
 */
refusalTerms.push(
  /\b(?:AI|LLMs?|large\s+language\s+models?|language\s+models?)(?:\s+-\s*|\s*-\s+|\s{2,})(?:generat\w*|assist\w*|written|authored|produced|tools?|tooling|agents?|code|coding)\b/i,
);

/**
 * The AI terms of a text by where they start, each with its place in
 * reading order (assistance terms, then the refusal wordings outside
 * reported rules), and the longest one's length; the last block's are
 * kept, as it is asked about twice in a row (same text, same sentences).
 */
type Terms = { text?: string; sentenceOf?: (span: Span) => Span; byStart: (Span & { order: number })[]; longest: number };
let lastTerms: Terms = { byStart: [], longest: 0 };
function termsOf(text: string, sentenceOf: (span: Span) => Span) {
  if (lastTerms.text === text && lastTerms.sentenceOf === sentenceOf) return lastTerms;
  const reportedIn = new Map<string, boolean>();
  const reported = (span: Span) => {
    const sentence = sentenceOf(span);
    const key = `${sentence.start}:${sentence.end}`;
    if (!reportedIn.has(key)) reportedIn.set(key, othersRule.test(text.slice(sentence.start, sentence.end)));
    return reportedIn.get(key)!;
  };
  const terms = [
    ...assistanceSpans(text, cachedMatches),
    ...refusalTerms.flatMap((term) => cachedMatches(term, text)).filter((span) => !reported(span)),
  ];
  const byStart = terms.map((span, order) => ({ ...span, order })).sort((a, b) => a.start - b.start);
  lastTerms = { text, sentenceOf, byStart, longest: byStart.reduce((length, span) => Math.max(length, span.end - span.start), 0) };
  return lastTerms;
}

/**
 * Each rule phrase with the nearest AI-assistance term, when one is close
 * enough and in the same sentence to make them one rule; the span covers
 * both. A refusal in one sentence and an AI term in the next ("We do not
 * accept typo-only PRs. AI tools can help you find bugs.") are two things.
 * Of terms equally near, the first found wins. Each sentence is read for
 * reported rules once, and a phrase looks only at the terms that start
 * close enough to it, so many phrases and terms stay linear.
 */
function nearAssistance(
  text: string,
  rule: RegExp,
  sentenceOf: (span: Span) => Span,
) {
  const { byStart, longest } = termsOf(text, sentenceOf);
  const pairs: { phrase: Span; span: Span; term: Span }[] = [];
  for (const phrase of cachedMatches(rule, text)) {
    const sentence = sentenceOf(phrase);
    // A term within `proximity` of the phrase starts no earlier than this, nor later than `last`.
    const first = Math.max(sentence.start, phrase.start - proximity - longest);
    const last = Math.min(sentence.end, phrase.end + proximity);
    let nearest: (typeof byStart)[number] | undefined;
    for (let at = firstIndex(byStart.length, (index) => byStart[index].start >= first); at < byStart.length && byStart[at].start <= last; at++) {
      const candidate = byStart[at];
      if (candidate.end > sentence.end || gap(candidate, phrase) > proximity) continue;
      const distance = gap(candidate, phrase);
      if (!nearest || distance < gap(nearest, phrase) || (distance === gap(nearest, phrase) && candidate.order < nearest.order))
        nearest = candidate;
    }
    const term = nearest && { start: nearest.start, end: nearest.end };
    if (term)
      pairs.push({
        phrase,
        term,
        span: {
          start: Math.min(term.start, phrase.start),
          end: Math.max(term.end, phrase.end),
        },
      });
  }
  return pairs;
}

/**
 * What makes a refusal of AI help in `sentence` a rule the person weighs
 * rather than a ban (see classifyPolicy), each by its own words.
 */
function weighedFor(search: string, sentence: Span, term: Span) {
  const words = search.slice(sentence.start, sentence.end);
  return {
    // "You may use AI tools, but …": the AI use itself is allowed.
    permitted: cachedMatches(aiPermission, words).some(
      (match) =>
        sentence.start + match.end <= term.start &&
        term.start - (sentence.start + match.end) <= 20,
    ),
    // "… unless you have reviewed every line": a rule about how AI is used.
    conditional: conductCondition.test(words) && !maintainerPermission.test(words),
    // "Write the PR description and comments without AI": a rule about
    // the conversation, not the change; for the description it is the
    // project's own-words rule.
    aboutConversation: conversation.test(words) && !changeObject.test(words),
    // "Do not use AI to generate substantial pieces of code": how much is
    // too much is the person's call.
    sized: sizeQualifier.test(words) && !unsizedAiChange(words) && !refusalCarried.test(words),
    // "Listing AI tooling as a co-author … is not allowed": how AI help
    // is credited, not whether it may help; each refused thing counts.
    credited: weighedRefusal(words),
  };
}

/**
 * A document as a reader sees it: without soft hyphens, zero-width spaces
 * and joiners, word joiners or byte-order marks, which would hide a rule's
 * words from the patterns ("AI-gen\u00aderated", "Un\u200bacceptable
 * uses"). Lines stay where they are; quotes leave these characters out.
 */
const visibleText = (text: string) => text.replace(/[\u00ad\u200b-\u200d\u2060\ufeff]/g, "");

/**
 * The rules a project document states, by kind, each with a verbatim
 * quote (300 characters or fewer) and its 1-based line:
 * - `ban`: AI-assisted contributions refused. `contribution` is true when
 *   the same sentence names a PR, patch, contribution, commit, code,
 *   changes or what goes into this project, and the refusal is
 *   unconditional; only then does it block publishing.
 * - `disclose`: AI assistance must be disclosed (see `disclosureRule`).
 * - `understand`: contributors must be able to explain their changes.
 * - `area`: learning issues (good first issues and the like) are reserved
 *   for people, without AI.
 * - `agent`: text addressed to AI agents, or about agents acting by
 *   themselves; the person decides whether it applies.
 * - `own-words`: descriptions in the contributor's own words.
 * - `issue-first`: an issue before the work.
 *
 * The AI kinds need an AI term in an assistance sense within about 120
 * characters of the rule's words, in the same sentence; the others are
 * contribution rules that need no AI term. A refusal in a sentence that
 * lets contributors use AI ("You may use AI tools, but …"), or with a
 * condition they meet themselves ("… unless you have reviewed every
 * line"), or about comments and replies, is ambiguous: a ban without
 * contribution context, which never blocks. A refusal about the
 * description is an `own-words` rule.
 */
export function classifyPolicy(path: string, document: string): PolicyFinding[] {
  const text = visibleText(document);
  const findings: PolicyFinding[] = [];
  const seen = new Set<string>();
  // What a sentence's words say is read once per sentence, however many rules it holds.
  const perSentence = new Map<string, boolean>();
  const once = (what: string, sentence: Span, read: () => boolean) => {
    const key = `${what}:${sentence.start}:${sentence.end}`;
    if (!perSentence.has(key)) perSentence.set(key, read());
    return perSentence.get(key)!;
  };
  // The sentence ends of the block being read, found once for all its rules.
  let ends: number[][] = [];
  const add = (
    kind: PolicyKind,
    block: Block,
    search: string,
    match: Span,
    ambiguous = false,
  ) => {
    const sentence = sentenceAround(block.text, ends, match);
    const { quote, offset } = quoteOf(block.text, sentence, match);
    if (!quote.trim()) return;
    const key = `${kind}:${lineAt(block, offset)}:${quote}`;
    if (seen.has(key)) return;
    seen.add(key);
    findings.push({
      kind,
      path,
      line: lineAt(block, offset),
      quote,
      contribution:
        !ambiguous &&
        once("contribution", sentence, () => contributionContext.test(search.slice(sentence.start, sentence.end))),
    });
  };
  for (const block of blocks(documentProse(path, text))) {
    const search = searchable(block.text);
    perSentence.clear();
    // One AI finding per sentence: a reserved learning area wins over a ban.
    const decided = new Set<number>();
    ends = sentenceEnds(block.text);
    const sentenceOf = (span: Span) => sentenceAround(block.text, ends, span);
    for (const { phrase, span } of nearAssistance(search, learningIssues, sentenceOf)) {
      const sentence = sentenceOf(phrase);
      const words = search.slice(sentence.start, sentence.end);
      if (decided.has(sentence.start)) continue;
      if (once("area", sentence, () => prohibition.test(words) || reservation.test(words))) {
        add("area", block, search, span);
        decided.add(sentence.start);
      }
    }
    for (const { phrase, span, term } of nearAssistance(search, prohibition, sentenceOf)) {
      const sentence = sentenceOf(phrase);
      if (decided.has(sentence.start)) continue;
      decided.add(sentence.start);
      const words = search.slice(sentence.start, sentence.end);
      const agentTerm = /agent|bot/i.test(search.slice(term.start, term.end));
      const { permitted, conditional, aboutConversation, sized, credited } = weighedFor(search, sentence, term);
      // A long sentence about good first issues that refuses AI-generated
      // pull requests at its end still reserves the learning issues.
      if (learningIssues.test(words)) add("area", block, search, span);
      else if (agentTerm && autonomousAction.test(words))
        add("agent", block, search, span);
      else if (aboutConversation && /\bdescriptions?\b/i.test(words))
        add("own-words", block, search, span);
      else
        add(
          "ban",
          block,
          search,
          span,
          permitted || conditional || aboutConversation || sized || credited,
        );
    }
    for (const match of cachedMatches(addressedToAgents, search))
      add("agent", block, search, match);
    for (const match of cachedMatches(agentsActingAlone, search))
      add("agent", block, search, match);
    for (const sentence of splitSentences(block.text))
      if (asksForDisclosure(search.slice(sentence.start, sentence.end)))
        add("disclose", block, search, sentence);
    for (const [kind, rule] of [
      ["understand", understandingRule],
      ["own-words", ownWordsRule],
      ["issue-first", issueFirstRule],
    ] as const)
      for (const match of cachedMatches(rule, search)) add(kind, block, search, match);
  }
  const ordered = findings.sort((a, b) => a.line - b.line);
  // The reach is read from each kept quote (`withStoredReach`), once the 30 are chosen.
  if (ordered.length <= maxFindings) return ordered.map(withStoredReach);
  // Over 30, the rules that block publishing stay, then the rest in reading order.
  const kept = new Set(
    ordered
      .map((finding, index) => ({ blocking: blocksPublishing(finding), index }))
      .sort((a, b) => Number(b.blocking) - Number(a.blocking) || a.index - b.index)
      .slice(0, maxFindings)
      .map(({ index }) => index),
  );
  return ordered.filter((_, index) => kept.has(index)).map(withStoredReach);
}

/** A document's rules kept at most (`ContributionRules.findings` holds 30). */
const maxFindings = 30;
/**
 * The rules that can block publishing: contribution bans, reserved
 * learning issues, disclosure, and a ban that stops the quoted confirm.
 */
const blocksPublishing = (finding: PolicyFinding) =>
  (finding.kind === "ban" && finding.contribution) ||
  finding.kind === "area" ||
  finding.kind === "disclose" ||
  stopsQuotedConfirm(finding);

/**
 * A ban that refuses AI help itself or whose reach BELL can't tell
 * (`refusesAiHelp`), contribution named or not: while it stands, no
 * Learn-by-hand run gets the quoted confirm (shared/by-hand-rules.ts), so
 * no cap of the stored rules may leave it out.
 */
export function stopsQuotedConfirm(finding: PolicyFinding) {
  return finding.kind === "ban" && banReach(finding.quote) !== "output" && refusesAiHelp(finding.quote);
}

/**
 * A finding as BELL stores it (plan README §18.10): a `ban` with its
 * `reach` and, when it stops the quoted confirm, `stopsConfirm`; an `area`
 * rule with its `reach`; any other kind as it is. Both are read from the
 * quote again, so a stored value from another build never stands. The
 * classifier, the rules card's read, the checked list and the load of
 * rules an older build stored all go through it, so the client reads the
 * reach without the classifier.
 */
export function withStoredReach(finding: PolicyFinding): PolicyFinding {
  if (finding.kind !== "ban" && finding.kind !== "area") return finding;
  const { reach: _reach, stopsConfirm: _stops, ...rest } = finding;
  if (finding.kind === "area") return { ...rest, reach: areaReach(finding.quote) };
  return { ...rest, reach: banReach(finding.quote), ...(stopsQuotedConfirm(finding) ? { stopsConfirm: true as const } : {}) };
}

/** The project's own practice, not a rule for contributors: "We do not use AI tools in our release process". */
const ownPractice =
  /^\W*(?:we|maintainers?|reviewers?|the\s+(?:team|maintainers|reviewers|project|core\s+team)|this\s+project|our\s+(?:team|maintainers|reviewers|project|CI|bots?))\s+(?:(?:do|does|will)\s*(?:not|n't)|never)\s+(?:\w+\s+)?use\b/i;
/** An exception that is the contributor's own conduct: "unless you have reviewed every line". */
const conductException =
  /\b(?:unless|except)\b[^.;:]{0,60}?\b(?:review|understand|disclos|declar|attribut|label|mention|test|verif|check|explain|edit)\w*/i;

/**
 * Whether a ban's quote, read alone, refuses AI help as such: a ban with
 * nothing to weigh but whether it names a contribution ("AI assistance of
 * any kind is not accepted."). Not when it lets contributors use AI, makes
 * an exception for their own review, understanding, disclosure or testing,
 * is about the conversation, a size or the credit, or states the
 * project's own practice ("We do not use AI tools in our own release
 * process."); "except for translations" is no such exception. A quote
 * BELL can't read as a refusal refuses (the strict reading). Such a rule,
 * anywhere in a project's rules, stops the quoted confirm
 * (shared/by-hand-rules.ts).
 */
export function refusesAiHelp(quote: string) {
  const search = searchable(visibleText(quote));
  const whole = { start: 0, end: search.length };
  const pair = nearAssistance(search, prohibition, () => whole)[0];
  if (!pair) return true;
  if (ownPractice.test(search)) return false;
  const why = weighedFor(search, whole, pair.term);
  // A bare "unless" or "except" is no condition the person meets by their own conduct.
  const conduct =
    (conductCondition.test(search.replace(/\b(?:unless|except)\b/gi, blank)) || conductException.test(search)) &&
    !maintainerPermission.test(search);
  return !(why.permitted || conduct || why.aboutConversation || why.sized || why.credited);
}

