/** How close (in characters) an AI term and the rule's words must be. */
const proximity = 120;
const maxQuote = 300;

interface Span {
  start: number;
  end: number;
}

/** One paragraph or list item, its lines joined, with where each line starts. */
interface Block {
  text: string;
  starts: { offset: number; line: number }[];
}

/** Paragraphs, list items and headings each form a block; blank lines and code end one. */
function blocks(prose: ProseLine[]): Block[] {
  const result: Block[] = [];
  let current: Block | undefined;
  let previous = 0;
  for (const { line, text } of prose) {
    const blank = !text.trim();
    const starts =
      /^\s{0,3}#{1,6}\s/.test(text) ||
      /^\s*(?:[-*+]|\d{1,9}[.)])\s+/.test(text) ||
      line !== previous + 1;
    previous = line;
    if (blank || starts || !current) {
      if (current) result.push(current);
      current = blank ? undefined : { text: "", starts: [] };
      if (blank) continue;
    }
    // A continuation line's indent is layout, not part of the sentence.
    const piece = current!.text ? text.trimStart() : text;
    if (current!.text) current!.text += " ";
    current!.starts.push({ offset: current!.text.length, line });
    current!.text += piece;
    // A heading is a block of its own.
    if (/^\s{0,3}#{1,6}\s/.test(text)) {
      result.push(current!);
      current = undefined;
    }
  }
  if (current) result.push(current);
  return result;
}

function lineAt(block: Block, offset: number) {
  let line = block.starts[0].line;
  for (const start of block.starts) if (start.offset <= offset) line = start.line;
  return line;
}

const blank = (text: string) => " ".repeat(text.length);

/** `text` at `offset` inside `whole`, everything else in `whole` blanked. */
const keepOnly = (whole: string, offset: number, text: string) =>
  blank(whole.slice(0, offset)) + text + blank(whole.slice(offset + text.length));

/**
 * Inline code a policy writes a label or a trailer in ("`good first
 * issue`", "``Assisted-by:``"): words the reader is meant to read, not code.
 */
const quotedWords = /^\s*(?:(?:Assisted|Generated)-by:?|[\w\s'’-]*\bgood[- ]first[- ]issues?\b[\w\s'’-]*)\s*$/i;

/**
 * Text to search, positions kept: inline code and comment delimiters
 * blanked, emphasis markers too; what a reStructuredText role or link shows
 * (":ref:`AI generated <target>`", "`text <url>`_") stays readable.
 * Typographic apostrophes and hyphens read as typed ones ("don’t",
 * "AI‑generated"), one character for one, so a rule written with them is
 * found; quotes keep the file's own characters.
 */
function searchable(text: string) {
  return text
    .replace(/[\u2018\u2019\u02bc\u2032]/g, "'")
    .replace(/[\u2010\u2011]/g, "-")
    .replace(
      /:[\w.+-]+:`([^`]*)`|`([^`<]*?)\s*<[^`>]*>`_{1,2}/g,
      (whole: string, role: string | undefined, link: string | undefined) => {
        const shown = (role ?? link ?? "").replace(/\s*<[^>]*>\s*$/, "");
        return keepOnly(whole, whole.indexOf("`") + 1, shown);
      },
    )
    .replace(/`([^`]*)`/g, (code, inside: string) =>
      quotedWords.test(inside) ? keepOnly(code, 1, inside) : blank(code),
    )
    .replace(/<!--|-->/g, blank)
    .replace(/\*\*|__|(?<![\w*])\*(?=\w)|(?<=\w)\*(?![\w*])|(?<![\w_])_(?=\w)|(?<=\w)_(?![\w_])/g, blank);
}

/**
 * Where sentences end: after . ! or ? (and any closing bracket, quote or
 * emphasis marker) before a space or the end, never inside "e.g.", "i.e."
 * or "etc." ("(Copilot, ChatGPT, etc.) are not allowed").
 */
const sentenceEnd = /(?<!\b(?:e\.g|i\.e|etc))[.!?](["'’”)\]*_]*)(?=\s|$)/gi;

/**
 * The sentence around a span: from the end of the sentence before it to
 * the end of the one it ends in. An HTML comment's delimiters end a
 * sentence too, so a rule in a comment is quoted without the text after it.
 */
function sentenceAround(text: string, span: Span): Span {
  const boundaries = [
    ...[...text.matchAll(sentenceEnd)].map((match) => [
      match.index + 1,
      match.index + match[0].length,
    ]),
    ...[...text.matchAll(/<!--|-->/g)].map((match) => [
      match.index,
      match.index + match[0].length,
    ]),
  ].sort((a, b) => a[0] - b[0]);
  let start = 0;
  let end = text.length;
  for (const [before, after] of boundaries) {
    if (after <= span.start) start = after;
    else if (before >= span.end) {
      end = before;
      break;
    }
  }
  return { start, end };
}

/** A verbatim quote of at most 300 characters, without Markdown markers at its edges. */
function quoteOf(text: string, sentence: Span, match: Span) {
  let { start, end } = sentence;
  if (end - start > maxQuote) {
    const room = Math.max(0, maxQuote - (match.end - match.start));
    start = Math.max(sentence.start, match.start - Math.floor(room / 2));
    end = Math.min(sentence.end, start + maxQuote);
    start = Math.max(sentence.start, end - maxQuote);
  }
  let quote = text.slice(start, end);
  let offset = start;
  const lead =
    /^(?:\s|<!--|>|#{1,6}\s|[-*+]\s|\d{1,9}[.)]\s|\[[ xX]\]\s|\*\*|__)+/.exec(quote);
  if (lead) {
    quote = quote.slice(lead[0].length);
    offset += lead[0].length;
  }
  quote = quote.replace(/(?:\s|-->|\*\*|__)+$/, "");
  return { quote: quote.slice(0, maxQuote), offset };
}

function allMatches(pattern: RegExp, text: string): Span[] {
  const global = new RegExp(
    pattern.source,
    pattern.flags.includes("g") ? pattern.flags : `${pattern.flags}g`,
  );
  return [...text.matchAll(global)].map((match) => ({
    start: match.index,
    end: match.index + match[0].length,
  }));
}

const gap = (a: Span, b: Span) => Math.max(0, b.start - a.end, a.start - b.end);

/**
 * "No LLMs for patches / pull requests.", "No AI for issues.": a model
 * named for what it must not be used on is AI help too (DESIGN v1.2 F14,
 * Zig's README). The classifier's rules only; disclosure checks don't use it.
 */
const noAiFor =
  /\bno\s+(?:AI|LLMs?|large\s+language\s+models?|language\s+models?|chatbots?|generative\s+AI|gen[- ]?AI)(?:\s+(?:tools?|models?|assistants?))?\s+for\s+(?:patch(?:es)?|pull\s+requests?|PRs?|issues?|comments?|contributions?)\b/i;

/**
 * Each rule phrase with the nearest AI-assistance term, when one is close
 * enough and in the same sentence to make them one rule; the span covers
 * both. A refusal in one sentence and an AI term in the next ("We do not
 * accept typo-only PRs. AI tools can help you find bugs.") are two things.
 */
function nearAssistance(
  text: string,
  rule: RegExp,
  sentenceOf: (span: Span) => Span,
) {
  const terms = [...assistanceSpans(text), ...allMatches(noAiFor, text)];
  const pairs: { phrase: Span; span: Span; term: Span }[] = [];
  for (const phrase of allMatches(rule, text)) {
    const sentence = sentenceOf(phrase);
    const term = terms
      .filter(
        (candidate) =>
          candidate.start >= sentence.start &&
          candidate.end <= sentence.end &&
          gap(candidate, phrase) <= proximity,
      )
      .sort((a, b) => gap(a, phrase) - gap(b, phrase))[0];
    if (term)
      pairs.push({
        phrase,
        term,
        span: {
          start: Math.min(term.start, phrase.start),
          end: Math.max(term.end, phrase.end),
        },
      });
  }
  return pairs;
}

/**
 * The rules a project document states, by kind, each with a verbatim
 * quote (300 characters or fewer) and its 1-based line:
 * - `ban`: AI-assisted contributions refused. `contribution` is true when
 *   the same sentence names a PR, patch, contribution, commit, code,
 *   changes or what goes into this project, and the refusal is
 *   unconditional; only then does it block publishing.
 * - `disclose`: AI assistance must be disclosed (see `disclosureRule`).
 * - `understand`: contributors must be able to explain their changes.
 * - `area`: learning issues (good first issues and the like) are reserved
 *   for people, without AI.
 * - `agent`: text addressed to AI agents, or about agents acting by
 *   themselves; the person decides whether it applies.
 * - `own-words`: descriptions in the contributor's own words.
 * - `issue-first`: an issue before the work.
 *
 * The AI kinds need an AI term in an assistance sense within about 120
 * characters of the rule's words, in the same sentence; the others are
 * contribution rules that need no AI term. A refusal in a sentence that
 * lets contributors use AI ("You may use AI tools, but …"), or with a
 * condition they meet themselves ("… unless you have reviewed every
 * line"), or about comments and replies, is ambiguous: a ban without
 * contribution context, which never blocks. A refusal about the
 * description is an `own-words` rule.
 */
export function classifyPolicy(path: string, text: string): PolicyFinding[] {
  const findings: PolicyFinding[] = [];
  const seen = new Set<string>();
  const add = (
    kind: PolicyKind,
    block: Block,
    search: string,
    match: Span,
    ambiguous = false,
  ) => {
    const sentence = sentenceAround(block.text, match);
    const { quote, offset } = quoteOf(block.text, sentence, match);
    if (!quote.trim()) return;
    const key = `${kind}:${lineAt(block, offset)}:${quote}`;
    if (seen.has(key)) return;
    seen.add(key);
    findings.push({
      kind,
      path,
      line: lineAt(block, offset),
      quote,
      contribution:
        !ambiguous &&
        contributionContext.test(search.slice(sentence.start, sentence.end)),
    });
  };
  // reStructuredText has no fences: its "~~~" lines are section adornments.
  const prose = /\.rst$/i.test(path) ? restProse(text) : rawProse(text);
  for (const block of blocks(prose)) {
    const search = searchable(block.text);
    // One AI finding per sentence: a reserved learning area wins over a ban.
    const decided = new Set<number>();
    const sentenceOf = (span: Span) => sentenceAround(block.text, span);
    for (const { phrase, span } of nearAssistance(search, learningIssues, sentenceOf)) {
      const sentence = sentenceOf(phrase);
      const words = search.slice(sentence.start, sentence.end);
      if (decided.has(sentence.start)) continue;
      if (prohibition.test(words) || reservation.test(words)) {
        add("area", block, search, span);
        decided.add(sentence.start);
      }
    }
    for (const { phrase, span, term } of nearAssistance(search, prohibition, sentenceOf)) {
      const sentence = sentenceOf(phrase);
      if (decided.has(sentence.start)) continue;
      decided.add(sentence.start);
      const words = search.slice(sentence.start, sentence.end);
      const agentTerm = /agent|bot/i.test(search.slice(term.start, term.end));
      // "You may use AI tools, but …": the AI use itself is allowed.
      const permitted = allMatches(aiPermission, words).some(
        (match) =>
          sentence.start + match.end <= term.start &&
          term.start - (sentence.start + match.end) <= 20,
      );
      // "… unless you have reviewed every line": a rule about how AI is used.
      const conditional =
        conductCondition.test(words) && !maintainerPermission.test(words);
      // "Write the PR description and comments without AI": a rule about
      // the conversation, not the change; for the description it is the
      // project's own-words rule.
      const aboutConversation =
        conversation.test(words) && !changeObject.test(words);
      // "Do not use AI to generate substantial pieces of code": how much is
      // too much is the person's call.
      const sized = sizeQualifier.test(words);
      // "Listing AI tooling as a co-author … is not allowed": how AI help
      // is credited, not whether it may help; each refused thing counts.
      const credited = weighedRefusal(words);
      // A long sentence about good first issues that refuses AI-generated
      // pull requests at its end still reserves the learning issues.
      if (learningIssues.test(words)) add("area", block, search, span);
      else if (agentTerm && autonomousAction.test(words))
        add("agent", block, search, span);
      else if (aboutConversation && /\bdescriptions?\b/i.test(words))
        add("own-words", block, search, span);
      else
        add(
          "ban",
          block,
          search,
          span,
          permitted || conditional || aboutConversation || sized || credited,
        );
    }
    for (const match of allMatches(addressedToAgents, search))
      add("agent", block, search, match);
    for (const match of allMatches(agentsActingAlone, search))
      add("agent", block, search, match);
    for (const sentence of splitSentences(block.text))
      if (asksForDisclosure(search.slice(sentence.start, sentence.end)))
        add("disclose", block, search, sentence);
    for (const [kind, rule] of [
      ["understand", understandingRule],
      ["own-words", ownWordsRule],
      ["issue-first", issueFirstRule],
    ] as const)
      for (const match of allMatches(rule, search)) add(kind, block, search, match);
  }
  return findings
    .sort((a, b) => a.line - b.line)
    .slice(0, 30);
}

/**
 * A permission: what follows "does not apply to", "it's fine to", or "is
 * allowed to"/"not prohibited to", or what comes before "is out of
 * scope", "is fine", "are acceptable".
 */
const permission =
  /\b(?:does|do)\s+not\s+apply\s+to\b|\bit(?:['’]s|\s+is)\s+fine\s+to\b|\bnot\s+prohibited\b|\bout\s+of\s+scope\b|\b(?:is|are)\s+(?:acceptable|fine|permitted|allowed)\b/gi;
/** Where the words a permission covers end: a condition, a contrast or a duty. */
const permissionEnd =
  /;|\b(?:but|provided|as\s+long\s+as|so\s+long\s+as|if|unless|except|however|although|though|whereas|while|when|should|must|needs?|ha(?:ve|s)\s+to|expected|required)\b/gi;
/** A negation or an exception among the permitted words drops the permission ("for anything other than debugging"). */
const permissionNegated =
  /\b(?:not|no|never|neither|nor|without|cannot|forbid\w*|prohibit\w*|ban(?:s|ned)?|disallow\w*|unacceptable|avoid\w*|other\s+than|apart\s+from|aside\s+from|besides|excluding|instead\s+of|rather\s+than|beyond)\b|n['’]t\b/i;
/** A permission for some people only ("only for maintainers") is no carve-out for the person. */
const permissionScoped =
  /\b(?:only|solely|exclusively|maintainers?|committers?|core|staff|employees?|team\s+members?)\b/i;
/** A permission that waits for somebody's approval, anywhere in its sentence ("if a maintainer approves"). */
const othersApproval = /\b(?:approv\w*|permission|consent|sign[- ]?off|agree\w*|ask(?:s|ed)?\s+(?:you|for)|invit\w*)\b/i;
/** A contrast right after the permission that takes it back: "fine in your fork, but not in this repository". */
const contrastTakesBack = /^\W*(?:but\s+)?(?:not|never|no)\b/i;
/** Somebody else's view, a rule of the past or one not decided: never the project's permission. */
const notTheProjects =
  /\b(?:no\s+longer|anymore|used\s+to|previously|formerly|until\s+recently|whether|myths?|misconceptions?|(?:some|many|other)\s+(?:people|contributors|users|folks|projects)|people\s+(?:often\s+|sometimes\s+)?(?:think|believe|say|claim|assume)|(?:you|they|others)\s+(?:may|might)\s+(?:think|believe|hear|have\s+heard)|(?:it\s+is|it['’]s)\s+(?:often\s+|commonly\s+|widely\s+|sometimes\s+)?(?:said|claimed|believed|assumed|thought))\b/i;
/** The next sentence takes it back: "Just kidding: it is not." */
const takenBack =
  /^\W*(?:just\s+kidding|kidding|not\s+really|nope|(?:it|that|this)\s+(?:is|was)(?:\s+not|n['’]t)\b|(?:it|that|this)\s+no\s+longer\b)/i;
/** A sentence about AI help, as carve-outs are. */
const aiMention =
  /\b(?:AI|LLMs?|large\s+language\s+models?|language\s+models?|generative|chatbots?|ChatGPT|Copilot|Claude|Codex|Gemini|machine[- ]learning|artificial\s+intelligence)\b/i;
/** A heading or lead-in naming uses that are fine, or ones that are not. */
const acceptableHeading = /(?<![\w-])(?:acceptable|allowed|permitted|fine|ok|okay)\b/i;
const headingTopic = /\b(?:uses?|usage|AI|LLMs?|tools?)\b/i;
const refusingHeading =
  /\b(?:unacceptable|not\s+(?:\w+\s+)?(?:acceptable|allowed|permitted|ok|okay|fine)|disallowed|forbidden|prohibited|banned|never|don['’]t|do\s+not|avoid)\b/i;
/** A "Yes" that answers a question about using AI, unless it says "but please don't". */
const yesAnswer = /^\W*yes\b/i;
/** A "no", a "not", an exception or a "please don't" in a Yes answer or the sentence after it. */
const yesButDont =
  /\b(?:no|not|never|nope|don['’]t|do\s+not|avoid\w*|refrain\w*|except\w*|unless|instead|rather\s+than)\b|n['’]t\b/i;
/** A Yes that says nothing more, or only points to a caveat: the question's kinds stand. */
const plainYes = /^\W*yes\b[\s,.!;:-]*(?:$|(?:but\s+)?(?:see|note|remember|keep\s+in\s+mind|be\s+(?:aware|careful))\b)/i;
/** A question about the person asking using AI ("Can I use …?", "Is it OK to …?"), not about others. */
const askerUsesAi =
  /^\W*(?:(?:can|may|could)\s+(?:I|we|you|one|contributors?|newcomers?)\b|(?:is\s+it|it['’]s)\s+(?:ok|okay|fine|acceptable|allowed|permitted|alright)\b|(?:am\s+I|are\s+(?:we|you|contributors?|newcomers?))\s+(?:allowed|permitted)\b)/i;
const listItem = /^\s*(?:[-*+]|\d{1,9}[.)])\s+/;

/**
 * The words of a sentence that a permission at `phrase` covers (`start`
 * to `end`): up to the next condition after "does not apply to", "fine
 * to" or "allowed to", else back to the previous one. `clause` ends the
 * clause the permission is in.
 */
function permittedWords(words: string, phrase: Span): Span & { clause: number } {
  const ends = allMatches(permissionEnd, words);
  const clause = ends.find((end) => end.start >= phrase.end)?.start ?? words.length;
  if (/to$/i.test(words.slice(phrase.start, phrase.end)) || /^\s+to\b/i.test(words.slice(phrase.end)))
    return { start: phrase.end, end: clause, clause };
  const start = ends.filter((end) => end.end <= phrase.start).at(-1)?.end ?? 0;
  return { start, end: phrase.start, clause };
}

/**
 * Carve-outs of a project's AI rules (DESIGN v1.2 F12): what the same
 * document says some uses of AI are fine for, read deterministically and
 * conservatively, each with the help kinds the F12 word table finds in it
 * (`carveOutKinds`; nothing else counts). A sentence about AI counts in a
 * permission context ("does not apply to", "out of scope", "is fine",
 * "it's fine to", "not prohibited") for the words the permission covers
 * only, and a question about using AI counts when it is answered "Yes"
 * (never "Yes, but please don't"); a list item counts under a heading or
 * lead-in that names acceptable or allowed uses. Nothing counts under an
 * "unacceptable" or "not allowed" heading, and a sentence that is itself
 * a ban or a reserved-issue rule never does. Each `ban` and `area`
 * finding of the document gets the first three as `allows`; agent runs
 * never read them. Server only: the rules card calls it when it reads
 * the rules, and no client module does, so the word table stays out of
 * the client.
 */
export function attachCarveOuts(path: string, text: string, findings: PolicyFinding[]): PolicyFinding[] {
  const ruled = (finding: PolicyFinding) => finding.kind === "ban" || finding.kind === "area";
  const rules = findings.filter(ruled);
  if (!rules.length) return findings;
  // A sentence that is itself a ban or a reserved-issue rule is never its carve-out.
  const allows = readCarveOuts(path, text)
    .filter(
      (carveOut) =>
        !rules.some((rule) => rule.quote.includes(carveOut.quote) || carveOut.quote.includes(rule.quote)),
    )
    .slice(0, 3);
  if (!allows.length) return findings;
  return findings.map((finding) =>
    ruled(finding)
      ? { ...finding, allows: allows.map((allowance) => ({ ...allowance, kinds: [...allowance.kinds] })) }
      : finding,
  );
}

/** Every carve-out of a document, in reading order (see attachCarveOuts). */
function readCarveOuts(path: string, text: string): PolicyAllowance[] {
  const rest = /\.rst$/i.test(path);
  const raw = text.split(/\r?\n/);
  const all = blocks(rest ? restProse(text) : rawProse(text));
  // A heading, a bold line or a lead-in ending in ":" (not a directive), or a reStructuredText title.
  const headingOf = (block: Block) => {
    const plain = block.text.replace(/:[\w.+-]+:`[^`]*`/g, "").trim();
    const last = block.starts.at(-1)!.line;
    const heading =
      /^#{1,6}\s/.test(plain) ||
      /^(?:\*\*|__)[^*_]+(?:\*\*|__)$/.test(plain) ||
      (plain.endsWith(":") && plain.length <= 160 && !listItem.test(block.text) && !/^\.\.\s/.test(plain)) ||
      (rest && restAdornment.test(raw[last] ?? ""));
    return heading && plain.length <= 160 ? searchable(plain) : undefined;
  };
  const nearestHeading = (index: number, skip: (block: Block) => boolean) => {
    for (let at = index - 1; at >= 0; at--) {
      const heading = headingOf(all[at]);
      if (heading !== undefined) return heading;
      if (!skip(all[at])) return undefined;
    }
    return undefined;
  };
  const found: PolicyAllowance[] = [];
  const add = (block: Block, quote: { quote: string; offset: number }, kinds: HelpKind[]) => {
    if (kinds.length && quote.quote.trim() && !found.some((other) => other.quote === quote.quote))
      found.push({ line: lineAt(block, quote.offset), quote: quote.quote, kinds });
  };
  all.forEach((block, index) => {
    const under = nearestHeading(index, () => true);
    if (under !== undefined && (refusingHeading.test(under) || notTheProjects.test(under))) return;
    const search = searchable(block.text);
    // A list item under "Acceptable uses" (only list items between them).
    const lead = listItem.test(block.text) ? nearestHeading(index, (other) => listItem.test(other.text)) : undefined;
    const whole = { start: 0, end: block.text.length };
    if (
      lead !== undefined &&
      acceptableHeading.test(lead) &&
      headingTopic.test(lead) &&
      !permissionScoped.test(lead) &&
      block.text.length <= 300 &&
      !permissionNegated.test(search) &&
      !permissionScoped.test(search) &&
      !notTheProjects.test(search)
    )
      add(block, quoteOf(block.text, whole, whole), carveOutKinds(search));
    const sentences = splitSentences(block.text);
    sentences.forEach((sentence, at) => {
      const words = search.slice(sentence.start, sentence.end);
      if (!aiMention.test(words)) return;
      // A question about the person using AI, answered "Yes" in the next sentence or block.
      if (/\?\W*$/.test(words)) {
        if (!askerUsesAi.test(words)) return;
        const following = all[index + 1];
        const next = sentences[at + 1]
          ? { block, sentence: sentences[at + 1] }
          : following && { block: following, sentence: splitSentences(following.text)[0] };
        if (!next?.sentence) return;
        const answered = searchable(next.block.text);
        const answer = answered.slice(next.sentence.start, next.sentence.end);
        // The answer and the sentence after it: "Yes. But please don't." is no Yes.
        const after = splitSentences(next.block.text).find((other) => other.start >= next.sentence.end);
        const said = answered.slice(next.sentence.start, after?.end ?? next.sentence.end);
        if (!yesAnswer.test(answer) || yesButDont.test(said) || permissionScoped.test(said)) return;
        // "Yes, for understanding the code": only what the answer names too.
        const kinds = carveOutKinds(words).filter((kind) => plainYes.test(answer) || carveOutKinds(answer).includes(kind));
        const asked = quoteOf(block.text, sentence, sentence);
        const yes = quoteOf(next.block.text, next.sentence, next.sentence);
        const quote = `${asked.quote} ${yes.quote}`;
        if (quote.length <= 300) add(block, { quote, offset: asked.offset }, kinds);
        return;
      }
      // Somebody else's view, a past or undecided rule, or one the next sentence takes back.
      const following = sentences[at + 1];
      if (notTheProjects.test(words) || (following && takenBack.test(search.slice(following.start, following.end)))) return;
      for (const phrase of allMatches(permission, words)) {
        const covered = permittedWords(words, phrase);
        // The permitted words and what qualifies them up to the condition, the permission's own words left out.
        const qualified = `${words.slice(covered.start, Math.max(covered.start, phrase.start))} ${words.slice(phrase.end, covered.clause)}`;
        if (permissionNegated.test(qualified)) continue;
        if (contrastTakesBack.test(words.slice(covered.clause).replace(/^\s*;/, ""))) continue;
        // A role or somebody's approval anywhere after the permitted words, conditions included.
        const rest = words.slice(covered.start);
        if (permissionScoped.test(rest) || othersApproval.test(rest)) continue;
        const quote = quoteOf(block.text, sentence, {
          start: sentence.start + Math.min(phrase.start, covered.start),
          end: sentence.start + Math.max(phrase.end, covered.end),
        });
        // A sentence over 300 characters is quoted around the permission: only its quoted words count.
        const from = Math.max(sentence.start + covered.start, quote.offset);
        const to = Math.min(sentence.start + covered.end, quote.offset + quote.quote.length);
        const kinds = to > from ? carveOutKinds(search.slice(from, to)) : [];
        if (kinds.length) return add(block, quote, kinds);
      }
    });
  });
  return found;
}

/** The sentences of a text, split after . ! or ? and at comment delimiters. */
function splitSentences(text: string): Span[] {
  const spans: Span[] = [];
  let at = 0;
  while (at < text.length) {
    const span = sentenceAround(text, { start: at, end: at + 1 });
    spans.push({ start: Math.max(span.start, at), end: span.end });
    at = Math.max(span.end, at + 1);
  }
  return spans.filter((span) =>
    text.slice(span.start, span.end).replace(/<!--|-->/g, "").trim(),
  );
}

const aiTerm =
  "(?:AI|LLMs?|large language models?|generative|gen[- ]?AI|artificial intelligence|machine[- ]generated|Copilot|ChatGPT|Claude|Codex)\\b";
const discloseVerb =
  "(?:disclos\\w*|declar\\w*|mention|indicate|state|convey|tell us|let us know)";
const disclosedPassive =
  "(?:disclosed|declared|mentioned|indicated|stated|labell?ed|marked|flagged|noted)";

/** Lines that ask for a disclosure, in either word order. */
const disclosurePattern = new RegExp(
  [
    // "Please disclose any use of AI tools", "tell us if you used an LLM".
    `\\b${discloseVerb}\\b[^.\\n]{0,80}\\b${aiTerm}`,
    // "AI-assisted contributions must be disclosed", "LLM use should be noted",
    // "if you use AI tools, you must disclose it".
    `\\b${aiTerm}[^.\\n]{0,80}\\b(?:must|should|please|needs? to|has to|have to|is required to|are required to|shall)\\b(?!\\s*(?:not|n't)\\b)(?:[^.\\n]{0,40}\\b${disclosedPassive}\\b|\\s+(?:\\w+\\s+)?${discloseVerb}\\b)`,
    // "If you used AI tools, say so in the PR description."
    `\\b${aiTerm}[^.\\n]{0,80}\\bsay so\\b`,
    // "We will not accept AI-generated contributions without disclosure."
    `\\b${aiTerm}[^.\\n]{0,80}\\bwithout\\s+(?:\\w+\\s+)?(?:disclos\\w*|declar\\w*|attribution|labell?ing)\\b`,
  ].join("|"),
  "i",
);

/**
 * The patterns above also fit lines about an AI feature ("state whether
 * the AI module changed", "let us know if you need help with the AI
 * backend"), so a line counts only when it is about using AI to make the
 * contribution: also AI "involved in" making it (Mesa) or the content
 * "made with the help of" AI (Forgejo), never AI "involved in" a crash.
 */
const aiUse =
  /\b(?:us(?:e|es|ed|ing|age)|assist\w*|generated|wr(?:ote|itten)|authored|produced)\b|\binvolved\s+in\s+(?:the\s+)?(?:creative|making|writing|creating|coming|authoring|developing|preparing|producing|designing)\b|\b(?:made|created|written|prepared|done)\s+with\s+(?:the\s+)?help\s+of\b/i;

/** A template heading or checkbox: "## AI disclosure", "[ ] AI usage disclosed". */
const disclosureHeading =
  /\b(?:AI|LLM)[- ](?:assistance |usage |use )?disclos\w*/i;

/** "Do not mention AI" and the like are not disclosure rules. */
const negated =
  /\b(?:do not|don't|never|no need to|not required to)\s+(?:\w+\s+){0,2}(?:disclos|declar|mention|state|indicate|convey|say so)/i;

/**
 * A request to name the tool in a trailer: "use a commit message trailer
 * like Assisted-by: <name of code assistant>".
 */
const trailerRequest =
  /\b(?:use|add|include|append|with|like|such as|via)\b[^.\n]{0,60}\b(?:Assisted|Generated)-by\b/i;

/** Whether one line of prose asks contributors to disclose AI assistance. */
const asksForDisclosure = (prose: string) =>
  !negated.test(prose) &&
  (disclosureHeading.test(prose) ||
    trailerRequest.test(prose) ||
    (disclosurePattern.test(prose) && aiUse.test(prose)));

/**
 * The first contributing-guide or template line that asks for an
 * AI-assistance disclosure, with its source; code blocks and comments are
 * ignored, like the other rule quotes.
 */
export function disclosureRule(
  sources: readonly DraftSource[],
): DraftRuleQuote | undefined {
  for (const source of sources) {
    if (source.kind !== "contributing" && source.kind !== "template") continue;
    const lines = source.content.split("\n");
    const index = markdownProse(source.content).findIndex(asksForDisclosure);
    if (index < 0) continue;
    return {
      sourceId: source.id,
      label: source.label,
      quote: lines[index]
        .replace(/\*\*|__/g, "")
        .trim()
        .replace(/^[-*>#\s]+/, "")
        .replace(/^\[[ xX]\]\s*/, "")
        .slice(0, 200),
    };
  }
  return undefined;
}

/** A trailer naming the tool that helped, as kernel, LLVM and ASF policies ask. */
const toolTrailer = /^\s*(?:Assisted|Generated)-by:\s*\S/im;
const disclosureTool = [
  // In the person's own description, a model or tool named with a verb of
  // help is a disclosure, whatever else it is next to.
  writtenToolName,
  new RegExp(String.raw`\b${modelWords}\b`, flags),
  new RegExp(
    String.raw`\b(?:us(?:e|ed|ing)|use\s+of|with|via|by|from)\s+(?:an?\s+)?(?:AI|LLMs?)\b|\bAI[- ](?:help|support)\b`,
    flags,
  ),
];
const disclosureVerb =
  /\b(?:us(?:e|ed|es|ing)|assist\w*|generat\w*|wr(?:ote|itten)|drafted|helped|help\s+(?:from|of))\b/i;
/**
 * The help a Learn-by-hand guide gives: explain, answer, review, point
 * out, hint and guide, in all their forms. They count as disclosure verbs
 * only for a clean Learn-by-hand run (`hasAiDisclosure`'s `helpVerbs`):
 * in an agent run "Claude reviewed this" must not pass a disclosure rule
 * while the agents wrote the change (lead decision 2026-10-20).
 */
const helpVerb =
  /\b(?:explain(?:s|ed|ing)?|answer(?:s|ed|ing)?|review(?:s|ed|ing)?|point(?:s|ed|ing)?\s+out|hint(?:s|ed|ing)?|guid(?:e|es|ed|ing))\b/gi;
/** A negation among the three words before a help verb: "not reviewed", "never explained", "not explained or reviewed". */
const helpNegation = /\b(?:not|never|no|nor|without)\b|n't\b/i;
/** A help verb of the clause that no negation comes just before. */
const namesHelp = (clause: string) =>
  [...clause.matchAll(helpVerb)].some(
    (match) =>
      !helpNegation.test(clause.slice(0, match.index).trim().split(/\s+/).slice(-3).join(" ")),
  );
const namesAssistance = (text: string) =>
  assistanceSpans(text).length > 0 || disclosureTool.some((term) => term.test(text));

/**
 * A disclosure field of a PR template, "AI usage disclosure: …",
 * "AI-assisted: …", "AI used: …" or "Use of AI: …", with what follows it.
 */
const disclosureField =
  /^\s*(?:[-*+]\s+)?(?:\*\*|__)?(?:(?:AI|LLM)[- ]?(?:(?:usage|use|assistance|tools?)\s+disclosure|disclosure|usage|use|used|assistance|assisted)|use\s+of\s+(?:AI|LLMs?))(?:\*\*|__)?\s*:\s*(?:\*\*|__)?\s*(.*)$/i;
/**
 * A sentence that says no AI helped: "No AI tools were used.", "I did not
 * use AI", "written without AI assistance", "not AI-generated".
 */
const deniesAssistance = new RegExp(
  [
    String.raw`^\W*(?:no|none|zero)\b`,
    String.raw`\b(?:did|do|does|was|were|is|are|have|has|had)(?:\s*not|n't)\s+(?:\w+\s+){0,2}?(?:use|used|using|involve|involved|need|needed|rel(?:y|ied)|assisted|generated|written|AI|any)\b`,
    String.raw`\bwithout\s+(?:the\s+)?(?:any\s+)?(?:use\s+of\s+|help\s+(?:of|from)\s+|using\s+)?(?:an?\s+)?(?:AI|LLMs?|generative|ChatGPT|Copilot|Claude|Codex|Gemini|Cursor|assistance|tools?)\b`,
    String.raw`\bnot\s+(?:\w+\s+)?(?:AI|LLM)[- ]?(?:generated|assisted|written)\b`,
    String.raw`\bnever\s+(?:used?|using)\b`,
  ].join("|"),
  "i",
);
/** "NO", "none" or "n/a" in a disclosure field. */
const deniedField = /^(?:no|none|n\/?a|nothing)\b/i;

/**
 * Whether the PR text says that AI helped: BELL's own disclosure line, an
 * `Assisted-by:` or `Generated-by:` trailer in the description or the
 * commit message, a template's disclosure field filled in with yes or a
 * tool ("AI usage disclosure: YES - Codex CLI wrote the patch"), or a
 * visible sentence of the description that names an AI tool together with
 * used, assisted, generated, wrote, drafted or helped. A field answered
 * "NO" is not a disclosure, and text in comments or code does not count:
 * maintainers would not see it.
 *
 * With `helpVerbs` (only for a clean Learn-by-hand run, which
 * `respectChecks` decides), explain, answer, review, point out, hint and
 * guide count too, unless a negation comes just before them ("Not
 * reviewed by AI." stays no disclosure). The default is false for good.
 */
export function hasAiDisclosure(
  body: string,
  commitMessage = "",
  options: { helpVerbs?: boolean } = {},
) {
  if (body.includes(aiDisclosureLine)) return true;
  if (toolTrailer.test(commitMessage)) return true;
  const lines = markdownProse(body);
  if (lines.some((line) => toolTrailer.test(line))) return true;
  const fields = lines.map((line) => disclosureField.exec(line)?.[1].trim());
  if (
    fields.some(
      (value) =>
        !!value &&
        !deniedField.test(value) &&
        (/^(?:yes|y)\b/i.test(value) || namesAssistance(value)),
    )
  )
    return true;
  const visible = lines
    .filter((_, index) => fields[index] === undefined || !deniedField.test(fields[index]!))
    .join(" ");
  // Each clause on its own: "Codex wrote the parser; the tests were not
  // AI-generated" and "Not reviewed by AI, but written with Copilot" still
  // disclose, "No AI tools were used." and "Disclosure: no AI was used" do not.
  return splitSentences(visible).some(({ start, end }) =>
    visible
      .slice(start, end)
      .split(/;|:\s|\bbut\b/i)
      .some(
        (clause) =>
          (disclosureVerb.test(clause) || (!!options.helpVerbs && namesHelp(clause))) &&
          namesAssistance(clause) &&
          !deniesAssistance.test(clause),
      ),
  );
}

const mentionsAi = new RegExp(String.raw`\b${aiTerm}`, "i");

/**
 * Headroom item 2 (DESIGN v1.2 F13): the first line of the PR text that
 * says no AI helped, quoted as written: BELL's agent disclosure line, a
 * disclosure field answered "no", or a sentence with a clause that
 * `deniesAssistance` matches, names AI and names none of the guide's help.
 * A Learn-by-hand run asks whether it means something else; nothing here
 * judges it true or false.
 */
export function assistanceDenial(body: string, commitMessage = "") {
  if (body.includes(aiDisclosureLine)) return aiDisclosureLine;
  for (const text of [body, commitMessage]) {
    const lines = markdownProse(text);
    const field = lines.find((line) => deniedField.test(disclosureField.exec(line)?.[1].trim() ?? ""));
    if (field) return field.trim();
    for (const block of blocks(lines.map((line, index) => ({ line: index + 1, text: line })))) {
      const visible = block.text.replace(/^\s*(?:[-*+>]|\d+[.)])\s+/, "");
      const denial = splitSentences(visible).find(({ start, end }) =>
        visible
          .slice(start, end)
          .split(/;|:\s|\bbut\b/i)
          .some((clause) => deniesAssistance.test(clause) && mentionsAi.test(clause) && !namesHelp(clause)),
      );
      if (denial) return visible.slice(denial.start, denial.end).trim();
    }
  }
  return undefined;
}
