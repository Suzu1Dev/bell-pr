/**
 * The words of a sentence that a permission at `phrase` covers (`start`
 * to `end`): up to the next condition after "does not apply to", "fine
 * to" or "allowed to", else back to the previous one. `clause` ends the
 * clause the permission is in.
 */
function permittedWords(words: string, phrase: Span): Span & { clause: number } {
  const ends = cachedMatches(permissionEnd, words);
  const clause = ends.find((end) => end.start >= phrase.end)?.start ?? words.length;
  if (/to$/i.test(words.slice(phrase.start, phrase.end)) || /^\s+to\b/i.test(words.slice(phrase.end)))
    return { start: phrase.end, end: clause, clause };
  const start = ends.filter((end) => end.end <= phrase.start).at(-1)?.end ?? 0;
  return { start, end: phrase.start, clause };
}

/**
 * Carve-outs of a project's AI rules (DESIGN v1.2 F12): what the same
 * document says some uses of AI are fine for, read deterministically and
 * conservatively, each with the help kinds the F12 word table finds in it
 * (`carveOutKinds`; nothing else counts). A sentence about AI counts in a
 * permission context ("does not apply to", "out of scope", "is fine",
 * "it's fine to", "not prohibited") for the words the permission covers
 * only, and a question about using AI counts when it is answered "Yes"
 * (never "Yes, but please don't"); a list item counts under a heading or
 * lead-in that names acceptable or allowed uses. Nothing counts under an
 * "unacceptable" or "not allowed" heading, and a sentence that is itself
 * a ban or a reserved-issue rule never does. Each `ban` and `area`
 * finding of the document gets the first three as `allows`; agent runs
 * never read them. Server only: the rules card calls it when it reads
 * the rules, and no client module does, so the word table stays out of
 * the client.
 */
export function attachCarveOuts(path: string, text: string, findings: PolicyFinding[]): PolicyFinding[] {
  const ruled = (finding: PolicyFinding) => finding.kind === "ban" || finding.kind === "area";
  const rules = findings.filter(ruled);
  if (!rules.length) return findings;
  // A sentence that is itself a ban or a reserved-issue rule is never its carve-out; the first three others count.
  const allows: PolicyAllowance[] = [];
  for (const carveOut of readCarveOuts(path, text)) {
    if (allows.length === 3) break;
    if (!rules.some((rule) => rule.quote.includes(carveOut.quote) || carveOut.quote.includes(rule.quote))) allows.push(carveOut);
  }
  if (!allows.length) return findings;
  return findings.map((finding) =>
    ruled(finding)
      ? { ...finding, allows: allows.map((allowance) => ({ ...allowance, kinds: [...allowance.kinds] })) }
      : finding,
  );
}

/**
 * Text no reader sees as the project's permission, blanked with its lines
 * kept: HTML comments and, in reStructuredText, comments (".. " lines that
 * are no directive or target, with their indented lines).
 */
function withoutComments(text: string, rest: boolean) {
  const blankLines = (part: string) => part.replace(/[^\n]/g, " ");
  if (!rest) return text.replace(/<!--[\s\S]*?(?:-->|$)/g, blankLines);
  let comment: number | undefined;
  return text
    .split("\n")
    .map((line) => {
      const indent = line.length - line.trimStart().length;
      if (comment !== undefined && (!line.trim() || indent > comment)) return blankLines(line);
      comment = /^\s*\.\.(?:\s|$)(?!\s*(?:[\w.+-]+::|_|\[|\|))/.test(line) ? indent : undefined;
      return comment === undefined ? line : blankLines(line);
    })
    .join("\n");
}
/** A lead-in that quotes or shows somebody else's text: "LLVM's policy says:", "for comparison", "an example policy". */
const reportedLead =
  /\b(?:says?|said|states?|stated|writes?|wrote|puts\s+it)\b\W*$|\bfor\s+comparison\b|\b(?:example|sample|template)\s+(?:polic(?:y|ies)|text|wording|rules?)\b/i;
/** A quote's attribution: "> — from another project's guide". */
const attribution = /(?:^|\s)(?:\u2014|\u2015|--)\s*\S/;
/** A list item marked as not fine: "❌ …", "No: …", "Not …". */
const markedNo = /^\s*(?:[-*+]|\d{1,9}[.)])\s+(?:\[[ xX]\]\s+)?(?:\u274c|\u2717|\u2718|\u2716|\u{1f6ab}|\u26d4|:x:|:no_entry(?:_sign)?:|(?:no|not|never|don['’]t|avoid)\b)/iu;

/**
 * Permission phrases read in one sentence: each reads the rest of its
 * sentence, and real sentences have one or two. Reading fewer can only
 * leave a rule blocked, never lift one.
 */
const maxPermissions = 8;

/** Every carve-out of a document, in reading order (see attachCarveOuts). */
function readCarveOuts(path: string, document: string): PolicyAllowance[] {
  const rest = /\.rst$/i.test(path);
  const text = withoutComments(visibleText(document), rest);
  const raw = text.split(/\r?\n/);
  const all = blocks(documentProse(path, text));
  // A Markdown indented code block: four spaces in, after a block that is no list item.
  const indentedCode = (index: number) =>
    !rest && /^(?: {4}|\t)/.test(raw[all[index].starts[0].line - 1] ?? "") && !(index && listItem.test(all[index - 1].text));
  // A heading, a bold line or a lead-in ending in ":" (not a directive), or a reStructuredText title.
  const headingOf = (block: Block) => {
    const plain = block.text.replace(/:[\w.+-]+:`[^`]*`/g, "").trim();
    const last = block.starts.at(-1)!.line;
    const heading =
      /^#{1,6}\s/.test(plain) ||
      /^(?:\*\*|__)[^*_]+(?:\*\*|__)$/.test(plain) ||
      (plain.endsWith(":") && plain.length <= 160 && !listItem.test(block.text) && !/^\.\.\s/.test(plain)) ||
      (rest && restAdornment.test(raw[last] ?? ""));
    return heading && plain.length <= 160 ? searchable(plain) : undefined;
  };
  // Each block read once, in one pass: its searched text, its sentences, whether it is a
  // heading and a list item, the nearest heading above it (`under`), the nearest one above
  // its run of list items (`aboveItems`) and the list item ending in ":" in that run (`colon`).
  const searches = all.map((block) => searchable(block.text));
  const sentencesOf = all.map((block) => splitSentences(block.text));
  const headings = all.map(headingOf);
  const items = all.map((block) => listItem.test(block.text));
  const under: (string | undefined)[] = [];
  const aboveItems: (string | undefined)[] = [];
  const colon: (number | undefined)[] = [];
  for (let index = 1; index < all.length; index++) {
    const previous = index - 1;
    under[index] = headings[previous] ?? under[previous];
    aboveItems[index] = headings[previous] ?? (items[previous] ? aboveItems[previous] : undefined);
    colon[index] = items[previous] ? (all[previous].text.trim().endsWith(":") ? previous : colon[previous]) : undefined;
  }
  const found: PolicyAllowance[] = [];
  const quoted = new Set<string>();
  const add = (block: Block, quote: { quote: string; offset: number }, kinds: HelpKind[]) => {
    if (!kinds.length || !quote.quote.trim() || quoted.has(quote.quote)) return;
    quoted.add(quote.quote);
    found.push({ line: lineAt(block, quote.offset), quote: quote.quote, kinds });
  };
  // A lead-in that names acceptable uses of AI, decided once for every list item under it.
  const acceptingLeads = new Map<string, boolean>();
  const accepting = (lead: string) => {
    if (!acceptingLeads.has(lead))
      acceptingLeads.set(lead, !refusingHeading.test(lead) && acceptableHeading.test(lead) && headingTopic.test(lead) && !permissionScoped.test(lead));
    return acceptingLeads.get(lead)!;
  };
  // The lead-in of a list item: a list item ending in ":" before it ("Not acceptable:"), else the heading.
  const itemLeads: string[] = [];
  const leadOf = (index: number) => {
    const item = colon[index];
    return item === undefined ? aboveItems[index] : (itemLeads[item] ??= searchable(all[item].text.replace(listItem, "")));
  };
  all.forEach((block, index) => {
    if (under[index] !== undefined && (refusingHeading.test(under[index]) || notTheProjects.test(under[index]) || reportedLead.test(under[index]))) return;
    if (indentedCode(index) || (/^\s*>/.test(block.text) && attribution.test(block.text))) return;
    const search = searches[index];
    // A list item under "Acceptable uses" (only list items between them), unless marked as not fine.
    const lead = items[index] && !markedNo.test(block.text) ? leadOf(index) : undefined;
    const whole = { start: 0, end: block.text.length };
    if (
      lead !== undefined &&
      accepting(lead) &&
      block.text.length <= 300 &&
      !permissionNegated.test(search) &&
      !permissionScoped.test(search) &&
      !notTheProjects.test(search)
    )
      add(block, quoteOf(block.text, whole, whole), carveOutKinds(search));
    const sentences = sentencesOf[index];
    sentences.forEach((sentence, at) => {
      const words = search.slice(sentence.start, sentence.end);
      if (!aiMention.test(words)) return;
      // A question about the person using AI (a "?" among the sentence's last non-word characters), answered "Yes" in the next sentence or block.
      if (words.slice(words.search(/\w\W*$/) + 1).includes("?")) {
        if (!askerUsesAi.test(words) || permissionScoped.test(words) || othersApproval.test(words) || notTheProjects.test(words))
          return;
        // What is asked ends at its condition: "… to write the code if I then debug it myself?"
        const asked = words.slice(0, questionCondition.exec(words)?.index ?? words.length);
        // The next sentence (in this block, else the first of the next), and the one after it.
        const [nextIndex, nextAt] = sentences[at + 1] ? [index, at + 1] : [index + 1, 0];
        const next = sentencesOf[nextIndex]?.[nextAt] && { block: all[nextIndex], sentence: sentencesOf[nextIndex][nextAt] };
        if (!next?.sentence) return;
        const answered = searches[nextIndex];
        const answer = answered.slice(next.sentence.start, next.sentence.end);
        // The answer and the sentence after it: "Yes. But please don't." is no Yes.
        const after = sentencesOf[nextIndex][nextAt + 1];
        const said = answered.slice(next.sentence.start, after?.end ?? next.sentence.end);
        if (!yesAnswer.test(answer) || yesButDont.test(said) || permissionScoped.test(said)) return;
        // "Yes, for understanding the code": only what the answer names too.
        const kinds = carveOutKinds(asked).filter((kind) => plainYes.test(answer) || carveOutKinds(answer).includes(kind));
        const question = quoteOf(block.text, sentence, sentence);
        const yes = quoteOf(next.block.text, next.sentence, next.sentence);
        const quote = `${question.quote} ${yes.quote}`;
        if (quote.length <= 300) add(block, { quote, offset: question.offset }, kinds);
        return;
      }
      // Somebody else's view, a past or undecided rule, or one the next sentence takes back.
      const following = sentences[at + 1];
      if (notTheProjects.test(words) || (following && takenBack.test(search.slice(following.start, following.end)))) return;
      for (const phrase of cachedMatches(permission, words).slice(0, maxPermissions)) {
        const covered = permittedWords(words, phrase);
        // The permitted words and what qualifies them up to the condition, the permission's own words left out.
        const qualified = `${words.slice(covered.start, Math.max(covered.start, phrase.start))} ${words.slice(phrase.end, covered.clause)}`;
        if (permissionNegated.test(qualified)) continue;
        if (contrastTakesBack.test(words.slice(covered.clause).replace(/^\s*;/, ""))) continue;
        // A permission inside a condition: "If using AI to debug is fine with your reviewer, …" (read after the last , or ;).
        const before = words.slice(0, Math.min(phrase.start, covered.start));
        if (subordinate.test(before.slice(Math.max(before.lastIndexOf(","), before.lastIndexOf(";")) + 1))) continue;
        // Taken back in its own sentence: "…, but changes made that way are not accepted."
        const after = words.slice(covered.clause);
        if (/^\W*but\b/i.test(after) && prohibition.test(after)) continue;
        // A role or somebody's approval anywhere after the permitted words, conditions included.
        const rest = words.slice(covered.start);
        if (permissionScoped.test(rest) || othersApproval.test(rest)) continue;
        const quote = quoteOf(block.text, sentence, {
          start: sentence.start + Math.min(phrase.start, covered.start),
          end: sentence.start + Math.max(phrase.end, covered.end),
        });
        // A sentence over 300 characters is quoted around the permission: only its quoted words count.
        const from = Math.max(sentence.start + covered.start, quote.offset);
        const to = Math.min(sentence.start + covered.end, quote.offset + quote.quote.length);
        const kinds = to > from ? carveOutKinds(search.slice(from, to)) : [];
        if (kinds.length) return add(block, quote, kinds);
      }
    });
  });
  return found;
}

/**
 * The sentences of a text, split after . ! or ? and at comment delimiters:
 * each runs from where the one before it ended to the first end after its
 * first character.
 */
function splitSentences(text: string): Span[] {
  const spans: Span[] = [];
  const ends = sentenceEnds(text);
  for (let at = 0, next = 0; at < text.length; ) {
    while (next < ends.length && ends[next][0] <= at) next++;
    const end = next < ends.length ? ends[next][0] : text.length;
    spans.push({ start: at, end });
    at = end;
  }
  return spans.filter((span) =>
    text.slice(span.start, span.end).replace(/<!--|-->/g, "").trim(),
  );
}

const aiTerm =
  "(?:AI|LLMs?|large language models?|generative|gen[- ]?AI|artificial intelligence|machine[- ]generated|Copilot|ChatGPT|Claude|Codex)\\b";
const discloseVerb =
  "(?:disclos\\w*|declar\\w*|mention|indicate|state|convey|tell us|let us know)";
const disclosedPassive =
  "(?:disclosed|declared|mentioned|indicated|stated|labell?ed|marked|flagged|noted)";

/** Lines that ask for a disclosure, in either word order. */
const disclosurePattern = new RegExp(
  [
    // "Please disclose any use of AI tools", "tell us if you used an LLM".
    `\\b${discloseVerb}\\b[^.\\n]{0,80}\\b${aiTerm}`,
    // "AI-assisted contributions must be disclosed", "LLM use should be noted",
    // "if you use AI tools, you must disclose it".
    `\\b${aiTerm}[^.\\n]{0,80}\\b(?:must|should|please|needs? to|has to|have to|is required to|are required to|shall)\\b(?!\\s*(?:not|n't)\\b)(?:[^.\\n]{0,40}\\b${disclosedPassive}\\b|\\s+(?:\\w+\\s+)?${discloseVerb}\\b)`,
    // "If you used AI tools, say so in the PR description."
    `\\b${aiTerm}[^.\\n]{0,80}\\bsay so\\b`,
    // "We will not accept AI-generated contributions without disclosure."
    `\\b${aiTerm}[^.\\n]{0,80}\\bwithout\\s+(?:\\w+\\s+)?(?:disclos\\w*|declar\\w*|attribution|labell?ing)\\b`,
  ].join("|"),
  "i",
);

/**
 * The patterns above also fit lines about an AI feature ("state whether
 * the AI module changed", "let us know if you need help with the AI
 * backend"), so a line counts only when it is about using AI to make the
 * contribution: also AI "involved in" making it (Mesa) or the content
 * "made with the help of" AI (Forgejo), never AI "involved in" a crash.
 */
const aiUse =
  /\b(?:us(?:e|es|ed|ing|age)|assist\w*|generated|wr(?:ote|itten)|authored|produced)\b|\binvolved\s+in\s+(?:the\s+)?(?:creative|making|writing|creating|coming|authoring|developing|preparing|producing|designing)\b|\b(?:made|created|written|prepared|done)\s+with\s+(?:the\s+)?help\s+of\b/i;

/** A template heading or checkbox: "## AI disclosure", "[ ] AI usage disclosed". */
const disclosureHeading =
  /\b(?:AI|LLM)[- ](?:assistance |usage |use )?disclos\w*/i;

/** "Do not mention AI" and the like are not disclosure rules. */
const negated =
  /\b(?:do not|don't|never|no need to|not required to)\s+(?:\w+\s+){0,2}(?:disclos|declar|mention|state|indicate|convey|say so)/i;

/**
 * A request to name the tool in a trailer: "use a commit message trailer
 * like Assisted-by: <name of code assistant>".
 */
const trailerRequest =
  /\b(?:use|add|include|append|with|like|such as|via)\b[^.\n]{0,60}\b(?:Assisted|Generated)-by\b/i;

/** Whether one line of prose asks contributors to disclose AI assistance. */
const asksForDisclosure = (prose: string) =>
  !negated.test(prose) &&
  (disclosureHeading.test(prose) ||
    trailerRequest.test(prose) ||
    (disclosurePattern.test(prose) && aiUse.test(prose)));

/**
 * The first contributing-guide or template line that asks for an
 * AI-assistance disclosure, with its source; code blocks and comments are
 * ignored, like the other rule quotes.
 */
export function disclosureRule(
  sources: readonly DraftSource[],
): DraftRuleQuote | undefined {
  for (const source of sources) {
    if (source.kind !== "contributing" && source.kind !== "template") continue;
    const lines = source.content.split("\n");
    const index = markdownProse(source.content).findIndex(asksForDisclosure);
    if (index < 0) continue;
    return {
      sourceId: source.id,
      label: source.label,
      quote: lines[index]
        .replace(/\*\*|__/g, "")
        .trim()
        .replace(/^[-*>#\s]+/, "")
        .replace(/^\[[ xX]\]\s*/, "")
        .slice(0, 200),
    };
  }
  return undefined;
}

/**
 * A trailer naming the tool that helped, as kernel, LLVM and ASF policies
 * ask, after spaces on its own line (each line is tried, so the spaces
 * never run on into the next).
 */
const toolTrailer = /^[^\S\n\r\u2028\u2029]*(?:Assisted|Generated)-by:\s*\S/im;
const disclosureTool = [
  // In the person's own description, a model or tool named with a verb of
  // help is a disclosure, whatever else it is next to.
  writtenToolName,
  new RegExp(String.raw`\b${modelWords}\b`, flags),
  new RegExp(
    String.raw`\b(?:us(?:e|ed|ing)|use\s+of|with|via|by|from)\s+(?:an?\s+)?(?:AI|LLMs?)\b|\bAI[- ](?:help|support)\b`,
    flags,
  ),
];
const disclosureVerb =
  /\b(?:us(?:e|ed|es|ing)|assist\w*|generat\w*|wr(?:ote|itten)|drafted|helped|help\s+(?:from|of))\b/i;
/**
 * The help a Learn-by-hand guide gives: explain, answer, review, point
 * out, hint and guide, in all their forms. They count as disclosure verbs
 * only for a clean Learn-by-hand run (`hasAiDisclosure`'s `helpVerbs`):
 * in an agent run "Claude reviewed this" must not pass a disclosure rule
 * while the agents wrote the change (lead decision 2026-10-20).
 */
const helpVerb =
  /\b(?:explain(?:s|ed|ing)?|answer(?:s|ed|ing)?|review(?:s|ed|ing)?|point(?:s|ed|ing)?\s+out|hint(?:s|ed|ing)?|guid(?:e|es|ed|ing))\b/gi;
/** A negation among the three words before a help verb: "not reviewed", "never explained", "not explained or reviewed". */
const helpNegation = /\b(?:not|never|no|nor|without)\b|n't\b/gi;
/**
 * A help verb of the clause that no negation comes just before, among the
 * three words up to it: one pass over the clause's words and negations.
 */
const namesHelp = (clause: string) => {
  const words = [...clause.matchAll(/\S+/g)];
  const negations = [...clause.matchAll(helpNegation)];
  let word = 0;
  let negation = 0;
  return [...clause.matchAll(helpVerb)].some(({ index }) => {
    while (word < words.length && words[word].index < index) word++;
    // With no word before it, the first word (at or after it) starts the search: no negation is before it.
    const from = words[Math.max(0, word - 3)]?.index ?? index;
    while (negation < negations.length && negations[negation].index < from) negation++;
    const next = negations[negation];
    return !next || next.index + next[0].length > index;
  });
};
const namesAssistance = (text: string) =>
  assistanceSpans(text).length > 0 || disclosureTool.some((term) => term.test(text));

/**
 * A disclosure field of a PR template, "AI usage disclosure: …",
 * "AI-assisted: …", "AI used: …" or "Use of AI: …", with what follows it.
 */
const disclosureField =
  /^\s*(?:[-*+]\s+)?(?:\*\*|__)?(?:(?:AI|LLM)[- ]?(?:(?:usage|use|assistance|tools?)\s+disclosure|disclosure|usage|use|used|assistance|assisted)|use\s+of\s+(?:AI|LLMs?))(?:\*\*|__)?\s*:\s*(?:\*\*|__)?\s*(.*)$/i;
/**
 * A sentence that says no AI helped: "No AI tools were used.", "I did not
 * use AI", "written without AI assistance", "not AI-generated".
 */
const deniesAssistance = new RegExp(
  [
    String.raw`^\W*(?:no|none|zero)\b`,
    String.raw`\b(?:did|do|does|was|were|is|are|have|has|had)(?:\s*not|n't)\s+(?:\w+\s+){0,2}?(?:use|used|using|involve|involved|need|needed|rel(?:y|ied)|assisted|generated|written|AI|any)\b`,
    String.raw`\bwithout\s+(?:the\s+)?(?:any\s+)?(?:use\s+of\s+|help\s+(?:of|from)\s+|using\s+)?(?:an?\s+)?(?:AI|LLMs?|generative|ChatGPT|Copilot|Claude|Codex|Gemini|Cursor|assistance|tools?)\b`,
    String.raw`\bnot\s+(?:\w+\s+)?(?:AI|LLM)[- ]?(?:generated|assisted|written)\b`,
    String.raw`\bnever\s+(?:used?|using)\b`,
  ].join("|"),
  "i",
);
/** "NO", "none" or "n/a" in a disclosure field. */
const deniedField = /^(?:no|none|n\/?a|nothing)\b/i;

/**
 * Whether the PR text says that AI helped: BELL's own disclosure line, an
 * `Assisted-by:` or `Generated-by:` trailer in the description or the
 * commit message, a template's disclosure field filled in with yes or a
 * tool ("AI usage disclosure: YES - Codex CLI wrote the patch"), or a
 * visible sentence of the description that names an AI tool together with
 * used, assisted, generated, wrote, drafted or helped. A field answered
 * "NO" is not a disclosure, and text in comments or code does not count:
 * maintainers would not see it.
 *
 * With `helpVerbs` (only for a clean Learn-by-hand run, which
 * `respectChecks` decides), explain, answer, review, point out, hint and
 * guide count too, unless a negation comes just before them ("Not
 * reviewed by AI." stays no disclosure). The default is false for good.
 */
export function hasAiDisclosure(
  body: string,
  commitMessage = "",
  options: { helpVerbs?: boolean } = {},
) {
  if (body.includes(aiDisclosureLine)) return true;
  if (toolTrailer.test(commitMessage)) return true;
  const lines = markdownProse(body);
  if (lines.some((line) => toolTrailer.test(line))) return true;
  const fields = lines.map((line) => disclosureField.exec(line)?.[1].trim());
  if (
    fields.some(
      (value) =>
        !!value &&
        !deniedField.test(value) &&
        (/^(?:yes|y)\b/i.test(value) || namesAssistance(value)),
    )
  )
    return true;
  const visible = lines
    .filter((_, index) => fields[index] === undefined || !deniedField.test(fields[index]!))
    .join(" ");
  // Each clause on its own: "Codex wrote the parser; the tests were not
  // AI-generated" and "Not reviewed by AI, but written with Copilot" still
  // disclose, "No AI tools were used." and "Disclosure: no AI was used" do not.
  return splitSentences(visible).some(({ start, end }) =>
    visible
      .slice(start, end)
      .split(/;|:\s|\bbut\b/i)
      .some(
        (clause) =>
          (disclosureVerb.test(clause) || (!!options.helpVerbs && namesHelp(clause))) &&
          namesAssistance(clause) &&
          !deniesAssistance.test(clause),
      ),
  );
}

const mentionsAi = new RegExp(String.raw`\b${aiTerm}`, "i");

/**
 * Headroom item 2 (DESIGN v1.2 F13): the first line of the PR text that
 * says no AI helped, quoted as written: BELL's agent disclosure line, a
 * disclosure field answered "no", or a sentence with a clause that
 * `deniesAssistance` matches, names AI and names none of the guide's help.
 * A Learn-by-hand run asks whether it means something else; nothing here
 * judges it true or false.
 */
export function assistanceDenial(body: string, commitMessage = "") {
  if (body.includes(aiDisclosureLine)) return aiDisclosureLine;
  for (const text of [body, commitMessage]) {
    const lines = markdownProse(text);
    const field = lines.find((line) => deniedField.test(disclosureField.exec(line)?.[1].trim() ?? ""));
    if (field) return field.trim();
    for (const block of blocks(lines.map((line, index) => ({ line: index + 1, text: line })))) {
      const visible = block.text.replace(/^\s*(?:[-*+>]|\d+[.)])\s+/, "");
      const denial = splitSentences(visible).find(({ start, end }) =>
        visible
          .slice(start, end)
          .split(/;|:\s|\bbut\b/i)
          .some((clause) => deniesAssistance.test(clause) && mentionsAi.test(clause) && !namesHelp(clause)),
      );
      if (denial) return visible.slice(denial.start, denial.end).trim();
    }
  }
  return undefined;
}
