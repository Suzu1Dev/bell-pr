// "Contributions must be entirely human-authored.": a contribution that
// must be written by humans only is a ban of AI help (plan README §18.10,
// W2G verifier follow-up 1). It blocks agent runs, and a fitted
// Learn-by-hand run never gets the quoted confirm for it, even with a
// carve-out beside it. The sentences are written for these tests.
import assert from "node:assert/strict";
import test from "node:test";
import { byHandRulesCase } from "./by-hand-rules.js";
import { respectChecks } from "./contribution.js";
import { banReach } from "./policy-reach.js";
import { attachCarveOuts, classifyPolicy } from "./project-policy.js";

const carveOut = "This policy does not apply to using AI to understand the code or to research APIs.";

function read(text: string) {
  const document = `# Contributing\n\n${text}\n\n${carveOut}\n`;
  const findings = attachCarveOuts("CONTRIBUTING.md", document, classifyPolicy("CONTRIBUTING.md", document));
  const rules = { checkedAt: "2026-10-20T10:00:00.000Z", findings, filesRead: ["CONTRIBUTING.md"] };
  return {
    bans: findings.filter((finding) => finding.kind === "ban").map((finding) => [finding.contribution, banReach(finding.quote)]),
    case: byHandRulesCase(rules, { learningIssue: false, now: "2026-10-20T09:00:00.000Z" }),
    agent: respectChecks({ body: "Retries a GET twice.", rules }, "en").map((check) => check.id),
  };
}

test("a contribution that must be written by humans only is a ban of AI help", () => {
  for (const text of [
    "Contributions must be entirely human-authored.",
    "All code must be written by humans.",
    "Patches must be 100% human-written.",
    "Pull requests must only be human-made.",
    "Every contribution must be written entirely by a human.",
    "Contributions **must** be entirely\nhuman‑authored.",
  ]) {
    const result = read(text);
    assert.deepEqual(result.bans, [[true, "assistance"]], text);
    assert.ok(result.agent.includes("ai-ban"), text);
    assert.deepEqual(result.case.case === "blocked" && result.case.reason, "reach", text);
  }
});

test("human-readable work, work by hand, reviews, decisions, commit messages or descriptions are no ban", () => {
  for (const text of [
    "Documentation must be human-readable.",
    "Code must be entirely human-readable and well commented.",
    "Bindings must be written by hand, not generated by bindgen.",
    "Every change must be reviewed by a human.",
    "Commit messages must be written by a human.",
    // Godot's contribution rules: who decides, not who writes.
    "All those decisions need to be made by a human.",
    "Some projects require code to be human-written; we only ask for a note.",
    "PR descriptions must be human-written.",
  ]) {
    const result = read(text);
    assert.deepEqual(result.bans, [], text);
    assert.ok(!result.agent.includes("ai-ban"), text);
  }
});
