/**
 * How reviewable a change is, read from its diff alone: which paths are
 * lockfiles, generated output, tests, docs or dependency manifests, and the
 * changed lines of each unified-diff patch. Pure and synchronous, so the
 * server, the draft tab and the demo agree.
 */
