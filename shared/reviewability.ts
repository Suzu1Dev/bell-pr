const basename = (filePath: string) => filePath.split("/").pop() ?? filePath;

/** A dependency lockfile, written by a package manager rather than a person. */
export function isLockfile(filePath: string) {
  return lockfileNames.has(basename(filePath));
}

/** Test directories, or `.test.` / `.spec.` / `_test` / `test_` file names. */
const testPathPattern =
  /(^|\/)(?:test|tests|__tests__|spec|specs)(\/|\.)|\.(?:test|spec)\.[^/]+$|_test\.[^/.]+$|(^|\/)test_[^/]+\.py$|Tests?\.(?:java|kt|cs|swift)$/;

export function isTestPath(filePath: string) {
  return testPathPattern.test(filePath);
}

/** Documentation: Markdown, reStructuredText, AsciiDoc and plain text, or anything under docs/. */
export function isDocsPath(filePath: string) {
  return (
    /(^|\/)docs\//.test(filePath) ||
    /\.(?:md|mdx|markdown|rst|adoc|txt)$/i.test(filePath)
  );
}

const manifestNames = new Set([
  "package.json",
  "deno.json",
  "composer.json",
  "Cargo.toml",
  "pyproject.toml",
  "Pipfile",
  "setup.py",
  "setup.cfg",
  "go.mod",
  "Gemfile",
  "pom.xml",
  "build.gradle",
  "build.gradle.kts",
  "mix.exs",
  "pubspec.yaml",
  "Package.swift",
]);

/** A file that declares the project's dependencies. */
export function isManifest(filePath: string) {
  const name = basename(filePath);
  return (
    manifestNames.has(name) ||
    /^requirements(?:[-_.][\w.-]+)?\.(?:txt|in)$/.test(name) ||
    /\.(?:gemspec|csproj|fsproj|vbproj)$/.test(name)
  );
}

/**
 * Names that are generated by convention, whatever the project says:
 * minified bundles, source maps, protobuf and other code generators' output.
 */
const knownGenerated =
  /\.min\.(?:js|css)$|\.map$|\.pb\.go$|_pb2(?:_grpc)?\.pyi?$|\.g\.dart$|\.freezed\.dart$|\.generated\.[^/]+$|\.designer\.cs$/;

/**
 * A gitattributes-style pattern as a regular expression: `*` and `?` stay
 * within one path segment, `**` crosses them, a pattern without a slash
 * matches the file name at any depth, a leading slash anchors it to the
 * root, and a trailing slash matches everything under that directory.
 */
function globPattern(pattern: string) {
  let glob = pattern.trim();
  const directory = glob.endsWith("/");
  if (directory) glob = glob.replace(/\/+$/, "");
  const anchored = glob.startsWith("/") || glob.includes("/");
  glob = glob.replace(/^\/+/, "");
  let source = "";
  for (let index = 0; index < glob.length; index++) {
    const char = glob[index];
    if (char === "*" && glob[index + 1] === "*") {
      // "**/" matches any number of directories, a final "**" everything.
      source += glob[index + 2] === "/" ? "(?:.*/)?" : ".*";
      index += glob[index + 2] === "/" ? 2 : 1;
    } else if (char === "*") source += "[^/]*";
    else if (char === "?") source += "[^/]";
    else source += char.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  const prefix = anchored ? "^" : "(?:^|/)";
  const suffix = directory ? "/" : "(?:$|/)";
  return new RegExp(`${prefix}${source}${suffix}`);
}

/**
 * Generated output: a conventional generated name, or a path matching one
 * of the project's own patterns (its `.gitattributes` `linguist-generated`
 * entries).
 */
export function isGeneratedPath(
  filePath: string,
  patterns: readonly string[] = [],
) {
  if (knownGenerated.test(filePath)) return true;
  return patterns.some((pattern) => {
    if (!pattern.trim()) return false;
    try {
      return globPattern(pattern).test(filePath);
    } catch {
      return false;
    }
  });
}

/** One line of a unified-diff patch body, with its line numbers. */
export interface PatchLine {
  /** "+" added, "-" removed, " " context. */
  kind: "+" | "-" | " ";
  text: string;
  /** The line in the old file; removed and context lines only. */
  oldLine?: number;
  /** The line in the new file; added and context lines only. */
  newLine?: number;
  /** Which hunk of the patch the line belongs to, from 0. */
  hunk: number;
}

/**
 * The lines of a patch after its file headers, hunk by hunk. A patch held
 * back for safety (a message instead of a diff) has none.
 */
export function patchLines(patch = ""): PatchLine[] {
  const lines: PatchLine[] = [];
  let oldLine = 0;
  let newLine = 0;
  let hunk = -1;
  const rows = patch.split("\n");
  // The patch's own final newline ends the last line; it is not a blank one.
  if (rows[rows.length - 1] === "") rows.pop();
  for (const line of rows) {
    const header = /^@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@/.exec(line);
    if (header) {
      oldLine = Number(header[1]);
      newLine = Number(header[2]);
      hunk++;
      continue;
    }
    // File headers come before the first hunk; "\ No newline" is not a line.
    if (hunk < 0 || line.startsWith("\\")) continue;
    if (line.startsWith("+"))
      lines.push({ kind: "+", text: line.slice(1), newLine: newLine++, hunk });
    else if (line.startsWith("-"))
      lines.push({ kind: "-", text: line.slice(1), oldLine: oldLine++, hunk });
    // A blank context line may have lost its leading space in transit.
    else if (line.startsWith(" ") || line === "")
      lines.push({
        kind: " ",
        text: line.slice(1),
        oldLine: oldLine++,
        newLine: newLine++,
        hunk,
      });
  }
  return lines;
}

/** Whether removed and added lines differ only in whitespace (and something changed). */
function sameIgnoringWhitespace(lines: PatchLine[]) {
  const removed = lines.filter((line) => line.kind === "-");
  const added = lines.filter((line) => line.kind === "+");
  if (!removed.length && !added.length) return false;
  const squash = (side: PatchLine[]) =>
    side.map((line) => line.text).join("").replace(/\s+/g, "");
  return squash(removed) === squash(added);
}

/** The whole patch changes nothing but whitespace. */
export function whitespaceOnlyPatch(patch?: string) {
  return sameIgnoringWhitespace(patchLines(patch));
}

/** How many hunks of the patch change nothing but whitespace. */
export function whitespaceOnlyHunks(patch?: string) {
  const hunks = new Map<number, PatchLine[]>();
  for (const line of patchLines(patch))
    hunks.set(line.hunk, [...(hunks.get(line.hunk) ?? []), line]);
  return [...hunks.values()].filter(sameIgnoringWhitespace).length;
}

/** One flagged change to a test file: a deleted test file, an added skip or a removed assertion. */
export interface WeakenedTest {
  /**
   * `<path>#<line>`: the new file's line for an added skip, `-<line>` (the
   * old file's line) for a removed assertion, 0 for a deleted file. Stable
   * while the diff is, so a saved reason stays attached to its item.
   */
  id: string;
  path: string;
  /** The line in the new file (added skips) or the old file (removed assertions); 0 for a deleted file. */
  line: number;
  /** The line's text, trimmed to 200 characters; empty for a deleted file. */
  text: string;
}

/** Added lines that skip or focus tests in common frameworks. */
const skipPattern =
  /\.only\s*\(|\.skip\s*\(|\b(?:it|test|describe)\.(?:skip|only)\b|\bx(?:it|test|describe)\s*\(|pytest\.mark\.(?:skip|skipif|xfail)\b|\bxfail\b|@(?:Ignore|Disabled)\b|#\[ignore\]|\bt\.Skip(?:Now|f)?\(|\bunittest\.skip\w*\b|\bself\.skipTest\(/;
/** Removed lines that asserted something. */
const assertionPattern = /\bassert\w*\b|\bexpect\s*\(|\bshould\.|\.should\b|\bt\.(?:Error|Fatal)f?\(/;
/** Assertions that check almost nothing, so they do not replace a stricter one. */
const looseAssertion =
  /\.(?:toBeDefined|toBeTruthy)\s*\(\s*\)|\.not\.toThrow\s*\(\s*\)|\bexpect\s*\(\s*true\s*\)|\bassert(?:\.ok)?\s*\(\s*true\s*\)|\bassert\s+True\b/;

/**
 * The removed assertions of one hunk that no added assertion replaces.
 * Editing an assertion (a new expected value) removes and adds a line, so
 * each added assertion stands for one removed line; a loose one
 * (`toBeDefined()`, `assert True`) stands only for a removed loose one.
 */
function unreplacedAssertions(lines: readonly PatchLine[]) {
  const removed = lines.filter(
    (line) => line.kind === "-" && assertionPattern.test(line.text),
  );
  const added = lines.filter(
    (line) => line.kind === "+" && assertionPattern.test(line.text),
  );
  let strict = added.filter((line) => !looseAssertion.test(line.text)).length;
  let loose = added.length - strict;
  const unreplaced = new Set<PatchLine>();
  for (const line of removed) {
    if (!looseAssertion.test(line.text)) continue;
    if (loose) loose--;
    else if (strict) strict--;
    else unreplaced.add(line);
  }
  for (const line of removed) {
    if (looseAssertion.test(line.text)) continue;
    if (strict) strict--;
    else unreplaced.add(line);
  }
  return unreplaced;
}

/**
 * Changes that weaken a project's tests (DESIGN F9): deleted test files,
 * added skips (`.only`, `.skip(`, `it.skip`, `xit`, `pytest.mark.skip`,
 * `xfail`, `@Ignore`, `#[ignore]`, `t.Skip(`) and removed `assert` or
 * `expect(` lines in test files that no assertion of the same hunk
 * replaces, or that a loose one replaces. Publishing waits until each has
 * a reason.
 */
export function weakenedTests(
  files: readonly { path: string; status?: string; patch?: string }[],
): WeakenedTest[] {
  const found = new Map<string, WeakenedTest>();
  const add = (path: string, line: number, text: string, removed = false) => {
    const id = `${path}#${removed ? "-" : ""}${line}`;
    if (!found.has(id))
      found.set(id, { id, path, line, text: text.trim().slice(0, 200) });
  };
  for (const file of files) {
    if (!isTestPath(file.path)) continue;
    if (file.status === "deleted") {
      add(file.path, 0, "");
      continue;
    }
    const lines = patchLines(file.patch);
    const unreplaced = new Set<PatchLine>();
    for (const hunk of new Set(lines.map((line) => line.hunk)))
      for (const line of unreplacedAssertions(lines.filter((line) => line.hunk === hunk)))
        unreplaced.add(line);
    for (const line of lines) {
      if (line.kind === "+" && skipPattern.test(line.text))
        add(file.path, line.newLine ?? 0, line.text);
      else if (unreplaced.has(line))
        add(file.path, line.oldLine ?? 0, line.text, true);
    }
  }
  return [...found.values()];
}

/** A dependency a manifest gains. */
export interface NewDependency {
  path: string;
  name: string;
}

/** Keys of package.json-like files that are not dependencies. */
const notDependencies = new Set([
  "name",
  "version",
  "description",
  "main",
  "module",
  "types",
  "typings",
  "license",
  "author",
  "homepage",
  "type",
  "node",
  "npm",
  "edition",
  "readme",
  "repository",
  "requires-python",
  "python",
]);

/** The package a manifest line names, when it looks like a dependency entry. */
function dependencyName(manifest: string, text: string) {
  const name = basename(manifest);
  const patterns =
    name === "go.mod"
      ? [/^\s*(?:require\s+)?([\w.-]+\.[\w.-]+\/\S+)\s+v\d/]
      : /^requirements/.test(name)
        ? [/^\s*([A-Za-z0-9][\w.-]*)\s*(?:\[[^\]]*\])?\s*(?:[=<>!~]=?|;|$)/]
        : name === "Gemfile" || name.endsWith(".gemspec")
          ? [/^\s*(?:gem|\w+\.add_(?:\w+_)?dependency)\s*\(?\s*['"]([^'"]+)['"]/]
          : name === "pom.xml"
            ? [/<artifactId>\s*([^<\s]+)\s*<\/artifactId>/]
            : /\.gradle(?:\.kts)?$/.test(name)
              ? [/^\s*(?:implementation|api|compileOnly|runtimeOnly|testImplementation)\s*\(?\s*['"][^:'"]+:([^:'"]+)/]
              : /\.(?:csproj|fsproj|vbproj)$/.test(name)
                ? [/<PackageReference\s+Include="([^"]+)"/]
                : [
                    // "name": "^1.2.3" in package.json, composer.json, deno.json
                    /^\s*"(@?[\w./-]+)"\s*:\s*"(?:[~^<>=*]|\d|v\d|npm:|workspace:|file:|git|github:|link:|latest\b)/,
                    // name = "1.2" or name = { … } in TOML manifests
                    /^\s*([A-Za-z0-9][\w.-]*)\s*=\s*["{]/,
                    // "requests>=2" in a pyproject dependency list
                    /^\s*"([A-Za-z0-9][\w.-]*)\s*(?:\[[^\]]*\])?\s*(?:[=<>!~]=?[^"]*)?"\s*,?\s*$/,
                  ];
  for (const pattern of patterns) {
    const match = pattern.exec(text);
    if (match && !notDependencies.has(match[1])) return match[1];
  }
  return undefined;
}

/** Dependencies that manifests gain: added entries whose name no removed line had. */
export function newDependencies(
  files: readonly { path: string; patch?: string }[],
): NewDependency[] {
  const result: NewDependency[] = [];
  for (const file of files) {
    if (!isManifest(file.path)) continue;
    const lines = patchLines(file.patch);
    const removed = new Set(
      lines
        .filter((line) => line.kind === "-")
        .map((line) => dependencyName(file.path, line.text))
        .filter(Boolean),
    );
    for (const line of lines) {
      if (line.kind !== "+") continue;
      const name = dependencyName(file.path, line.text);
      if (name && !removed.has(name) && !result.some((entry) => entry.path === file.path && entry.name === name))
        result.push({ path: file.path, name });
    }
  }
  return result.slice(0, 20);
}

/** BELL's size bands: green up to 100 changed lines, amber up to 400, red above 1,000 lines or 20 files. */
export type ReviewabilityBand = "small" | "medium" | "large" | "very-large";

export const reviewabilityBands = {
  small: 100,
  medium: 400,
  large: 1000,
  files: 20,
} as const;

export interface ReviewabilitySnapshot {
  /** Added plus removed lines, lockfiles and generated paths left out. */
  changedLines: number;
  /** Files changed, lockfiles and generated paths left out. */
  files: number;
  /** Test files among them. */
  testFilesChanged: number;
  /** A source file (not docs, not a test) changed. */
  sourceChanged: boolean;
  /** Only documentation changed. */
  docsOnly: boolean;
  newDependencies: NewDependency[];
  /**
   * How many independent parts the plan shows (see suggestSplit); absent or
   * 0 unless there are at least 2, since one part has nothing to split.
   */
  parts?: number;
  /** Changed files outside every plan task's scope; empty without a plan. */
  outsidePlan: string[];
  /** Files with hunks that change nothing but whitespace. */
  whitespaceOnly: string[];
  /** Changes to tests that need a reason before publishing. */
  weakened: WeakenedTest[];
  /** Not persisted: recomputed from the diff. */
  band: ReviewabilityBand;
  /** The project's last merged pull requests, as the real size reference. */
  mergedSizes?: MergedPrSize[];
}

/** Whether a path is inside one of a task's scopes: exact file names or directory prefixes ending with "/". */
export function inScope(filePath: string, scopes: readonly (readonly string[])[]) {
  return scopes.some((scope) =>
    scope.some((entry) =>
      entry.endsWith("/") ? filePath.startsWith(entry) : filePath === entry,
    ),
  );
}

/** A source file: not a test, not documentation, not a lockfile and not generated. */
function isSource(filePath: string, generated: readonly string[]) {
  return (
    !isTestPath(filePath) &&
    !isDocsPath(filePath) &&
    !isLockfile(filePath) &&
    !isGeneratedPath(filePath, generated)
  );
}

/**
 * The changed paths a plan task answers for: the files it integrated, or,
 * for a run saved before that was recorded, the files its scopes cover.
 */
export function planTaskPaths(changed: readonly string[], task: SplitTask) {
  const present = new Set(changed);
  return task.integratedFiles
    ? task.integratedFiles.filter((path) => present.has(path))
    : changed.filter((path) => inScope(path, [[...task.files]]));
}

/**
 * The issue numbers a plan task cites in its title or description, as `#42`.
 * A hash that follows a word character, `&` or `/` is not one: `C#7`, `&#39;`
 * and a URL fragment are not issues.
 */
export function taskIssues(task: Pick<SplitTask, "title" | "description">): string[] {
  const text = `${task.title}\n${task.description ?? ""}`;
  return [...new Set([...text.matchAll(/(?<![\w&/])#(\d{1,5})\b/g)].map((match) => `#${match[1]}`))];
}

/**
 * The groups of a change that the plan keeps apart, read from the plan alone:
 * tasks that depend on one another, changed the same file or cite the same
 * issue are one part, and a part needs at least one source file, so a task
 * that only adds a test or a document never makes a part of its own. This is
 * a suggestion, not a verdict that each part is a fix: the plan splits work
 * for speed, so one fix can span tasks, and one task can hold several fixes
 * in the same files (`issues` shows what each part cites).
 */
export function suggestSplit(
  files: readonly { path: string }[],
  tasks: readonly SplitTask[],
  generated: readonly string[] = [],
): SplitSuggestion {
  const changed = files.map((file) => file.path);
  const owned = tasks.map((task) => planTaskPaths(changed, task));
  const cited = tasks.map(taskIssues);

  // Union-find over the tasks: a dependency, a shared file or a shared issue joins two of them.
  const root = tasks.map((_, index) => index);
  const find = (index: number): number => {
    while (root[index] !== index) {
      root[index] = root[root[index]];
      index = root[index];
    }
    return index;
  };
  const join = (a: number, b: number) => {
    root[find(a)] = find(b);
  };
  const indexById = new Map(tasks.map((task, index) => [task.id, index]));
  const firstOwner = new Map<string, number>();
  const firstCiting = new Map<string, number>();
  tasks.forEach((task, index) => {
    for (const dependency of task.dependsOn ?? []) {
      const other = indexById.get(dependency);
      if (other !== undefined) join(index, other);
    }
    for (const path of owned[index]) {
      const earlier = firstOwner.get(path);
      if (earlier === undefined) firstOwner.set(path, index);
      else join(index, earlier);
    }
    for (const issue of cited[index]) {
      const earlier = firstCiting.get(issue);
      if (earlier === undefined) firstCiting.set(issue, index);
      else join(index, earlier);
    }
  });

  const components = new Map<number, number[]>();
  tasks.forEach((_, index) => {
    const key = find(index);
    components.set(key, [...(components.get(key) ?? []), index]);
  });

  const placed = new Set<string>();
  const parts: SplitPart[] = [];
  for (const indexes of [...components.values()].sort((a, b) => a[0] - b[0])) {
    const own = new Set(indexes.flatMap((index) => owned[index]));
    const paths = changed.filter((path) => own.has(path));
    if (!paths.some((path) => isSource(path, generated))) continue;
    for (const path of paths) placed.add(path);
    const named = indexes.map((index) => tasks[index]).find((task) => task.title.trim());
    parts.push({
      title: (named?.title ?? "").trim().slice(0, splitLimits.titleChars),
      paths,
      taskIds: indexes.map((index) => tasks[index].id),
      issues: [...new Set(indexes.flatMap((index) => cited[index]))],
    });
  }
  return { parts, unassigned: changed.filter((path) => !placed.has(path)) };
}

/** The number of independent parts, or 0 when there are fewer than 2. */
function partCount(
  files: readonly { path: string }[],
  tasks: readonly SplitTask[] | undefined,
  generated: readonly string[] | undefined,
) {
  const { parts } = suggestSplit(files, tasks ?? [], generated);
  return parts.length >= splitLimits.minContributions ? parts.length : 0;
}

/**
 * How reviewable the change is, from its files alone: size and band,
 * tests, new dependencies, files outside the plan and whitespace-only
 * hunks. The bands are BELL defaults after Google's small-CL guidance;
 * the project's own merged sizes are the real reference.
 */
export function reviewabilitySnapshot({
  files,
  planScopes,
  planTasks,
  generated,
  mergedSizes,
}: {
  files: readonly {
    path: string;
    additions: number;
    deletions: number;
    status?: string;
    patch?: string;
  }[];
  /** Each plan task's files (`run.team.tasks[].files`). */
  planScopes?: readonly (readonly string[])[];
  /** The plan's tasks, for the independent parts; without them there are none. */
  planTasks?: readonly SplitTask[];
  generated?: readonly string[];
  mergedSizes?: ReviewabilitySnapshot["mergedSizes"];
}): ReviewabilitySnapshot {
  const reviewable = files.filter(
    (file) => !isLockfile(file.path) && !isGeneratedPath(file.path, generated),
  );
  const changedLines = reviewable.reduce(
    (total, file) => total + file.additions + file.deletions,
    0,
  );
  const tests = reviewable.filter((file) => isTestPath(file.path));
  const docs = reviewable.filter((file) => isDocsPath(file.path));
  const scopes = (planScopes ?? []).filter((scope) => scope.length);
  const parts = partCount(files, planTasks, generated);
  const band: ReviewabilityBand =
    changedLines > reviewabilityBands.large ||
    reviewable.length > reviewabilityBands.files
      ? "very-large"
      : changedLines > reviewabilityBands.medium
        ? "large"
        : changedLines > reviewabilityBands.small
          ? "medium"
          : "small";
  return {
    changedLines,
    files: reviewable.length,
    testFilesChanged: tests.length,
    sourceChanged: reviewable.some(
      (file) => !isTestPath(file.path) && !isDocsPath(file.path),
    ),
    docsOnly: reviewable.length > 0 && docs.length === reviewable.length,
    ...(parts ? { parts } : {}),
    newDependencies: newDependencies(files),
    outsidePlan: scopes.length
      ? reviewable
          .filter((file) => !inScope(file.path, scopes))
          .map((file) => file.path)
      : [],
    whitespaceOnly: reviewable
      .filter((file) => whitespaceOnlyHunks(file.patch) > 0)
      .map((file) => file.path),
    weakened: weakenedTests(files),
    band,
    ...(mergedSizes?.length ? { mergedSizes: mergedSizes.slice(0, 3) } : {}),
  };
}
