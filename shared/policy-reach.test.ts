import assert from "node:assert/strict";
import test from "node:test";
import { areaReach, banReach } from "./policy-reach.js";

// Quotes verbatim from the policies BELL read (plan/direction-v1.2/research/policies.md §3-§4).

test("bans on AI help itself reach assistance: Gentoo, Zig and Asahi", () => {
  // Gentoo, Project:Council/AI_policy, wikitext line 4.
  assert.equal(
    banReach(
      "It is expressly forbidden to contribute to Gentoo any content that has been created with the assistance of Natural Language Processing artificial intelligence tools.",
    ),
    "assistance",
  );
  // Zig, README.md:489-493 on Codeberg.
  assert.equal(banReach("No LLMs for patches / pull requests."), "assistance");
  assert.equal(banReach("No LLMs for issues."), "assistance");
  // Asahi Linux, asahilinux.org/llm-policy.
  assert.equal(
    banReach("we broadly forbid the use of generative AI tooling for material contributions to Asahi Linux."),
    "assistance",
  );
});

test("bans on what AI generated reach output: QEMU, NetBSD, Servo and Rust's create", () => {
  // QEMU, docs/devel/code-provenance.rst:293-295.
  assert.equal(
    banReach(
      "Current QEMU project policy is to DECLINE any contributions which are believed to include or derive from AI generated content. This includes ChatGPT, Claude, Copilot, Llama and similar tools.",
    ),
    "output",
  );
  // NetBSD, commit-guidelines.html.
  assert.equal(
    banReach(
      "Code generated by a large language model or similar technology, such as GitHub/Microsoft's Copilot, OpenAI's ChatGPT, or Facebook/Meta's Code Llama, is presumed to be tainted code, and must not be committed without prior written approval by core.",
    ),
    "output",
  );
  // Servo book, src/policy/ai-usage.md:3.
  assert.equal(
    banReach("Contributions must not include content generated by large language models or other probabilistic tools"),
    "output",
  );
  // Rust, rust-forge src/policies/llm-usage.md:24 (the ban's own words).
  assert.equal(banReach("But not to **create**."), "output");
});

test("a ban whose words name both help and output, or neither, never reads as output only", () => {
  assert.equal(banReach("AI-assisted or AI-generated contributions are not accepted."), "assistance");
  assert.equal(banReach("Pull requests made with AI tools are not accepted."), "unknown");
  assert.equal(banReach("We do not accept AI contributions."), "unknown");
  // Mesa's "involved", one of the owner-approved classifier words.
  assert.equal(banReach("Contributions where AI was involved are not accepted."), "assistance");
});

test("reserved-issue rules: LLVM's 'use', matplotlib's output and Node.js's automate", () => {
  // LLVM, llvm/docs/AIToolPolicy.md:56-62.
  assert.equal(areaReach("AI tools must not be used to fix GitHub issues labelled `good first issue`."), "use");
  assert.equal(areaReach('Using AI tools to fix issues labelled as "good first issues" is forbidden'), "use");
  // matplotlib, doc/devel/contribute.rst:287-290.
  assert.equal(areaReach("pull requests that are AI generated will be closed."), "output");
  // Node.js, doc/contributing/ai-guidelines.md:40-42 (a quote-level case: the
  // v1.1 classifier finds no rule in it).
  assert.equal(
    areaReach('It\'s prohibited to use AI to automate fixes to issues marked as "good first issue".'),
    "automate",
  );
  assert.equal(areaReach("Good first issues are reserved for human contributors."), "unknown");
  // Use wins over output: the stricter reading.
  assert.equal(areaReach("Pull requests using AI-generated code for good first issues will be closed."), "use");
});
