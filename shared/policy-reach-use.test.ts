// A ban worded around AI "being used" in making a contribution reaches AI
// help itself, never only its output (plan README §18.10, W2G verifier
// follow-up 2): the quoted confirm must never read such a rule as an
// output ban with a carve-out. The sentences are written for these tests.
import assert from "node:assert/strict";
import test from "node:test";
import { byHandRulesCase } from "./by-hand-rules.js";
import { banReach } from "./policy-reach.js";
import { attachCarveOuts, classifyPolicy } from "./project-policy.js";

test("AI that may not be used in the creation of a contribution, at any stage or at all, reaches assistance", () => {
  for (const quote of [
    "No AI tools may be used in the creation of a contribution.",
    "AI tools must not be used in the creation of patches for this project.",
    "LLMs must not be used at any stage of a contribution.",
    "We do not accept contributions where an LLM was used at any stage.",
    "Generative AI may not be used at all.",
    "AI tools must not be used in any way when you prepare a pull request.",
    "AI must not be used for anything in the making of a patch.",
    "No language model may be used in creating code for this project.",
  ])
    assert.equal(banReach(quote), "assistance", quote);
  // What AI generated, used later, is still output: only its use in the making reaches help.
  for (const quote of [
    "Code generated by AI tools must not be used in contributions.",
    "Output of a language model is not accepted in pull requests.",
    "AI-generated code is not allowed.",
    "LLM output is not accepted in pull requests.",
  ])
    assert.equal(banReach(quote), "output", quote);
});

test("AI that was used, AI refused outright, human-only work and work made without AI reach assistance", () => {
  for (const quote of [
    "We decline contributions where AI was used.",
    "Large language models may not be used for patches.",
    "AI tools must never be used for pull requests.",
    "AI is banned from this project.",
    "Generative AI is strictly forbidden in contributions.",
    "LLMs are not allowed in pull requests.",
    "AI tools are not welcome here.",
    "Contributions must be entirely human-authored.",
    "All code must be written by humans.",
    "Contributions must be written without any help from AI tools.",
    "Patches must be made without AI.",
    "Code must be written without using an LLM.",
  ])
    assert.equal(banReach(quote), "assistance", quote);
  // AI named only as what made the thing refused: BELL can't tell the reach (W1A's case).
  assert.equal(banReach("Pull requests made with AI tools are not accepted."), "unknown");
  assert.equal(banReach("Pull requests made with an AI tool are not accepted."), "unknown");
});

test("an output ban worded around AI used in the creation of a contribution gives no quoted confirm", () => {
  const text = [
    "# AI policy",
    "",
    "No AI tools may be used in the creation of a contribution.",
    "",
    "This policy does not apply to other uses of AI, such as researching APIs or debugging.",
  ].join("\n");
  const rules = {
    checkedAt: "2026-10-20T10:00:00.000Z",
    findings: attachCarveOuts("AI_POLICY.md", text, classifyPolicy("AI_POLICY.md", text)),
    filesRead: ["AI_POLICY.md"],
  };
  assert.deepEqual(
    rules.findings.map((finding) => [finding.kind, finding.contribution, !!finding.allows]),
    [["ban", true, true]],
  );
  const result = byHandRulesCase(rules, { learningIssue: false, now: "2026-10-20T09:00:00.000Z" });
  assert.equal(result.case, "blocked");
  assert.deepEqual(result.case === "blocked" && [result.reason, result.reach], ["reach", "assistance"]);
});
