/**
 * What a quoted AI rule restricts (DESIGN v1.2 F12, F14 item 5). A ban
 * reaches AI help itself (`assistance`), only what AI generated
 * (`output`), or BELL can't tell (`unknown`). A reserved-issue rule is
 * worded around using AI (`use`), around AI-generated pull requests
 * (`output`), around automating fixes (`automate`), or unclear.
 *
 * The reach chooses the block copy of a Learn-by-hand run and is condition
 * (a) of the quoted confirm; it never changes an agent run's outcome.
 * Unknown is the strict reading: when a quote has words of both kinds, the
 * stricter one wins, so BELL never reads more permission into a rule than
 * its words give.
 */

export type BanReach = "assistance" | "output" | "unknown";
export type AreaReach = "use" | "output" | "automate" | "unknown";

/**
 * Help itself: "created with the assistance of", "the use of generative AI
 * tooling", "using AI", "No LLMs for patches", "AI was involved", "AI
 * help", "with the aid of AI".
 */
const assistanceWords =
  /\bassist(?:ance|ed|ing)?\b|\b(?:the\s+)?use\s+of\b|\bus(?:e|es|ed|ing)\s+(?:an?\s+|any\s+|the\s+)?(?:generative\s+)?(?:AI|LLMs?|large\s+language\s+models?|chatbots?|ChatGPT|Copilot|Claude|Codex|Gemini)\b|\bno\s+(?:AI|LLMs?)\s+for\b|\bhelp\s+(?:of|from)\b|\bwith\s+the\s+help\b|\binvolv\w*|\b(?:AI|LLM)[- ](?:help|aid|aided|support|input)\b|\baid\s+of\b|\baided\s+by\b/i;
/** Models and AI named as such: "AI", "generative AI", "LLMs", "chatbots". */
const aiNames = String.raw`(?:(?:generative\s+)?AI|gen[- ]?AI|LLMs?|large\s+language\s+models?|language\s+models?|chatbots?)`;
/**
 * AI help said other ways (plan README §18.10): AI that must not "be used"
 * in making a contribution ("No AI tools may be used in the creation of a
 * contribution", "LLMs must not be used at any stage", "… at all", "used
 * to create code"), AI that must not be used anywhere ("Large language
 * models may not be used for patches") or that "was used"; AI itself
 * refused outright ("AI is banned from this project", not "PRs made with
 * AI tools are not accepted", whose reach BELL can't tell); work that must
 * be human-authored, or made without AI ("written without any help from
 * AI tools" is `assistanceWords`). What AI generated being used later
 * ("Code generated by AI must not be used in contributions") stays output.
 */
const helpWordings = new RegExp(
  [
    String.raw`\b(?:be|been|being|was|were|is|are|gets?|got)\s+used\b(?:\s+[\w'’-]+){0,4}?\s+(?:in\s+(?:the\s+)?(?:creation|making|writing|authoring|development|preparation|production)\s+of|in\s+(?:creating|making|writing|authoring|developing|preparing|producing)|to\s+(?:create|make|write|author|develop|prepare|produce|generate)|at\s+any\s+(?:stage|point|time|step)|at\s+all|in\s+any\s+(?:way|form|part|stage|step|capacity|manner))\b`,
    String.raw`\b(?:was|were|has\s+been|have\s+been|had\s+been)\s+used\b`,
    String.raw`(?<!\b(?:with|by|using|from|of|via|through)\s+(?:(?:an?|any|the)\s+)?(?:generative\s+)?)\b${aiNames}(?:\s+(?:tools?|tooling|models?|assistants?))?\s+(?:(?:must|may|should|shall|can|will)\s*(?:not|n't)|(?:must|may|should|shall|can|will)\s+never|cannot)\s+(?:ever\s+)?be\s+used\b`,
    String.raw`(?<!\b(?:with|by|using|from|of|via|through)\s+(?:(?:an?|any|the)\s+)?(?:generative\s+)?)\b${aiNames}(?:\s+(?:tools?|tooling|use|usage|assistance|help))?\s+(?:is|are)\s+(?:(?:strictly|expressly|completely|entirely|totally|absolutely)\s+)?(?:banned|forbidden|prohibited|disallowed|unacceptable|not\s+(?:allowed|permitted|accepted|welcome|tolerated))\b`,
    String.raw`\bhuman[- ](?:authored|written|made|created|produced|crafted)\b|\b(?:authored|written|made|created|produced|crafted|done)\s+(?:(?:entirely|only|solely|exclusively|wholly|fully)\s+)?by\s+(?:a\s+|real\s+)?(?:humans?|people|persons?)\b`,
    String.raw`\bwithout\s+(?:the\s+)?(?:any\s+)?(?:(?:help|aid|assistance|use|input|involvement)\s+(?:of|from|by)\s+|using\s+|relying\s+on\s+)?(?:an?\s+|any\s+)?${aiNames}\b`,
  ].join("|"),
  "i",
);

/**
 * What AI made: "AI generated content", "Code generated by a large
 * language model", "not to create". Not "generative AI" (a kind of AI),
 * and not what was created, produced or written "with" AI, whose reach
 * BELL can't tell (as "made with AI tools").
 */
const outputWords =
  /\bgenerat(?!ive\b)\w*|\b(?:creat|produc)\w*\b(?!\s+(?:with|via|through)\b)|\bderiv\w*|\b(?:written|authored)\s+by\b|\boutput\b/i;

/**
 * Using AI on the issue at all: "AI tools must not be used to fix", "Using
 * AI tools to fix", "solved without AI", "No AI help", "No AI on good
 * first issues", "learning to code by hand" (not "No AI-generated pull
 * requests").
 */
const useWords =
  /\bus(?:e|es|ed|ing)\b|\bassist\w*|\bwithout\s+(?:the\s+)?(?:any\s+)?(?:(?:help|aid|assistance)\s+(?:of|from)\s+|using\s+)?(?:generative\s+)?(?:AI|LLMs?|chatbots?)\b|\b(?:AI|LLM)[- ](?:help|aid|support)\b|\bno\s+(?:generative\s+)?(?:AI|LLMs?)\b(?![- ]?(?:generat|written|authored|produced|created|made))|\bby\s+hand\b/i;

/** Automating the fix: "use AI to automate fixes" (Node.js). */
const automateWords = /\bautomat\w*/i;
/** A use of AI that is the automating itself: "use AI to automate". */
const useToAutomate = /\bus(?:e|es|ed|ing)\s+(?:\S+\s+){0,3}?to\s+automat\w*/gi;

/**
 * A quote as a reader sees it: the file's emphasis, code marks, link
 * targets and reStructuredText roles left out, typographic apostrophes
 * and hyphens read as typed ones, so "No **AI tools** may be used in the
 * *creation* of a contribution" reads as written.
 */
function plain(quote: string) {
  return quote
    .replace(/[\u00ad\u200b-\u200d\u2060\ufeff]/g, "")
    .replace(/[\u2018\u2019\u02bc\u2032]/g, "'")
    .replace(/[\u2010\u2011]/g, "-")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/:[\w.+-]+:`([^`<]*?)\s*(?:<[^`>]*>)?`|`([^`<]*?)\s*<[^`>]*>`_{1,2}/g, "$1$2")
    .replace(/\*\*|__|`|(?<![\w*])\*(?=\w)|(?<=\w)\*(?![\w*])|(?<![\w_])_(?=\w)|(?<=\w)_(?![\w_])/g, "");
}

/** The reach of a contribution ban, from its quote. */
export function banReach(quote: string): BanReach {
  const text = plain(quote);
  if (assistanceWords.test(text) || helpWordings.test(text)) return "assistance";
  if (outputWords.test(text)) return "output";
  return "unknown";
}

/**
 * The wording of a reserved-issue rule, from its quote: a use of AI on the
 * issue is the strictest, unless the only use named is automating fixes
 * ("use AI to automate fixes"); then automating, then a rule about
 * AI-generated pull requests.
 */
export function areaReach(quote: string): AreaReach {
  const text = plain(quote);
  if (useWords.test(text.replace(useToAutomate, " "))) return "use";
  if (automateWords.test(text)) return "automate";
  if (outputWords.test(text)) return "output";
  return "unknown";
}
