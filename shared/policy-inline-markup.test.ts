// A rule's words split by a link, inline HTML, an entity or emphasis inside
// a word ("use [ChatGPT](…)", "is <em>not</em> accepted", "AI&nbsp;tools",
// "AI-**generated**") were no rule at all, so next to an output ban with a
// carve-out such a rule refusing AI help itself never stopped the quoted
// confirm (W2G red team). The classifier reads them as a reader sees them;
// quotes keep the file's characters. The sentences are written for these
// tests.
import assert from "node:assert/strict";
import test from "node:test";
import { byHandRulesCase } from "./by-hand-rules.js";
import { areaReach, banReach } from "./policy-reach.js";
import { attachCarveOuts, classifyPolicy } from "./project-policy.js";

/** The findings' kinds; each quote is the file's own text. */
const kinds = (text: string) =>
  classifyPolicy("CONTRIBUTING.md", text).map((finding) => {
    assert.ok(text.includes(finding.quote), finding.quote);
    return [finding.kind, finding.contribution];
  });

test("links, inline HTML, entities and emphasis inside words don't hide a rule", () => {
  for (const text of [
    "Do not use [ChatGPT](https://chat.openai.com) or [Copilot][copilot] when contributing.",
    "<b>AI-generated</b> code is <em>not</em> accepted.",
    "AI-**generated** code is **not** accepted.",
    "**AI**-generated code is not accepted.",
    "AI&nbsp;tools must not be used when contributing.",
    "AI&#8209;generated code is not accepted.",
    "Code generated by [ChatGPT](https://chat.openai.com) is not accepted.",
  ])
    assert.deepEqual(kinds(text), [["ban", true]], text);
});

test("a link's target, a tag or a feature named in a link is still no rule", () => {
  for (const text of [
    "[AI features](docs/ai.md) are not accepted in core; use a plugin.",
    'Read the <a href="https://example.org/ai-generated-code-policy">policy</a> before you open a pull request.',
    "See [our notes](https://example.org/do-not-use-ai) on reviews.",
  ])
    assert.deepEqual(kinds(text), [], text);
});

test("the reach reads inline HTML and entities as a reader does", () => {
  assert.equal(banReach("Patches made with the <b>help</b> <i>of</i> AI are declined."), "assistance");
  assert.equal(banReach("The <em>use</em> of AI is not permitted in pull requests."), "assistance");
  assert.equal(banReach("AI&#8209;generated code is not accepted."), "output");
  assert.equal(areaReach("Good first issues must be solved <b>without</b> AI; AI-generated pull requests will be closed."), "use");
});

test("such a rule beside an output ban and its carve-out keeps the case blocked", () => {
  const text = [
    "AI-generated code is not accepted.",
    "",
    "This policy does not apply to using AI to understand the code.",
    "",
    "Do not use [ChatGPT](https://chat.openai.com) or [Copilot](https://github.com/features/copilot) when contributing.",
  ].join("\n");
  const findings = attachCarveOuts("CONTRIBUTING.md", text, classifyPolicy("CONTRIBUTING.md", text));
  const result = byHandRulesCase(
    { checkedAt: "2026-10-20T10:00:00.000Z", findings, filesRead: ["CONTRIBUTING.md"] },
    { learningIssue: false, now: "2026-10-20T09:00:00.000Z" },
  );
  assert.deepEqual(result.case === "blocked" && result.reason, "reach");
});
